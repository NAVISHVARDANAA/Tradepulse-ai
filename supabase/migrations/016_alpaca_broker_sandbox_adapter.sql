set
  code = 'alpaca-broker-sandbox',
  display_name = 'Alpaca Broker API sandbox',
  integration_status = 'sandbox',
  account_connection_enabled = false,
  live_order_routing_enabled = false,
  metadata = jsonb_build_object(
    'provider', 'alpaca',
    'environment', 'sandbox',
    'api_origin', 'https://broker-api.sandbox.alpaca.markets',
    'implementation_version', 'alpaca-broker-sandbox-v1',
    'authorization', 'server_side_basic',
    'capability', 'asset_read_probe_only',
    'custody', 'external_partner_required',
    'credentials', 'supabase_secrets_only'
  )
where code = 'broker-neutral-sandbox';

create table if not exists public.broker_adapter_probes (
  id bigint generated by default as identity primary key,
  provider_id bigint not null references public.broker_provider_registry(id),
  environment text not null default 'sandbox' check (environment = 'sandbox'),
  adapter_version text not null check (
    adapter_version = 'alpaca-broker-sandbox-v1'
  ),
  api_origin text not null check (
    api_origin = 'https://broker-api.sandbox.alpaca.markets'
  ),
  probe_kind text not null default 'asset_read' check (probe_kind = 'asset_read'),
  status text not null check (status in ('passed', 'failed')),
  http_status integer check (http_status is null or http_status between 100 and 599),
  latency_ms integer not null check (latency_ms between 0 and 10000),
  attempt_count integer not null check (attempt_count between 0 and 2),
  error_code text check (
    error_code is null or error_code in (
      'CONFIGURATION_INVALID',
      'SANDBOX_ROUTE_REJECTED',
      'AUTHENTICATION_FAILED',
      'RATE_LIMITED',
      'PROVIDER_UNAVAILABLE',
      'PROVIDER_RESPONSE_INVALID',
      'REQUEST_TIMEOUT'
    )
  ),
  live_order_routing_tested boolean not null default false check (
    not live_order_routing_tested
  ),
  created_at timestamptz not null default now(),
  check (
    (status = 'passed' and http_status = 200 and attempt_count > 0 and error_code is null)
    or (status = 'failed' and error_code is not null)
  )
);

create index if not exists idx_broker_adapter_probes_provider_created
  on public.broker_adapter_probes(provider_id, created_at desc);

alter table public.broker_adapter_probes enable row level security;

