create table if not exists public.academy_courses (
  slug text primary key check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  title text not null,
  short_title text not null,
  summary text not null,
  level text not null check (level in ('beginner', 'intermediate', 'advanced')),
  audience text not null,
  access_tier text not null default 'free' check (access_tier in ('free', 'pro', 'business')),
  language_code text not null default 'en' check (language_code ~ '^[a-z]{2}(?:-[A-Z]{2})?$'),
  estimated_minutes integer not null check (estimated_minutes between 1 and 10000),
  display_order smallint not null unique check (display_order > 0),
  learning_objectives jsonb not null default '[]'::jsonb check (jsonb_typeof(learning_objectives) = 'array'),
  published boolean not null default false,
  version text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.academy_lessons (
  slug text primary key check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  course_slug text not null references public.academy_courses(slug) on delete cascade,
  title text not null,
  summary text not null,
  lesson_kind text not null default 'reading' check (
    lesson_kind in ('reading', 'guided_practice', 'quiz', 'video')
  ),
  content jsonb not null default '[]'::jsonb check (jsonb_typeof(content) = 'array'),
  estimated_minutes integer not null check (estimated_minutes between 1 and 240),
  display_order smallint not null check (display_order > 0),
  published boolean not null default false,
  version text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (course_slug, display_order)
);

create table if not exists public.academy_quiz_questions (
  id bigint generated by default as identity primary key,
  lesson_slug text not null references public.academy_lessons(slug) on delete cascade,
  prompt text not null,
  options jsonb not null check (jsonb_typeof(options) = 'array' and jsonb_array_length(options) between 2 and 6),
  correct_option smallint not null check (correct_option >= 0),
  explanation text not null,
  display_order smallint not null check (display_order > 0),
  created_at timestamptz not null default now(),
  unique (lesson_slug, display_order)
);

create table if not exists public.academy_lesson_progress (
  user_id uuid not null references auth.users(id) on delete cascade,
  lesson_slug text not null references public.academy_lessons(slug) on delete cascade,
  status text not null default 'in_progress' check (status in ('in_progress', 'completed')),
  best_score numeric(5,2) check (best_score is null or best_score between 0 and 100),
  attempts integer not null default 0 check (attempts >= 0),
  last_position integer not null default 0 check (last_position >= 0),
  started_at timestamptz not null default now(),
  completed_at timestamptz,
  updated_at timestamptz not null default now(),
  primary key (user_id, lesson_slug)
);

create table if not exists public.academy_onboarding_state (
  user_id uuid primary key references auth.users(id) on delete cascade,
  tour_version text not null default 'product-tour-v1',
  current_step smallint not null default 0 check (current_step >= 0),
  completed_at timestamptz,
  skipped_at timestamptz,
  updated_at timestamptz not null default now()
);

create table if not exists public.academy_course_completions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  course_slug text not null references public.academy_courses(slug) on delete cascade,
  course_version text not null,
  final_score numeric(5,2) not null check (final_score between 0 and 100),
  verification_code text not null unique,
  issued_at timestamptz not null default now(),
  revoked_at timestamptz,
  unique (user_id, course_slug, course_version)
);

