create or replace view public.academy_catalog
with (security_invoker = true)
as
select
  course.slug,
  course.title,
  course.short_title,
  course.summary,
  course.level,
  course.audience,
  course.access_tier,
  course.language_code,
  course.estimated_minutes,
  course.display_order,
  course.learning_objectives,
  course.version,
  count(lesson.slug)::integer as lesson_count
from public.academy_courses course
left join public.academy_lessons lesson
  on lesson.course_slug = course.slug and lesson.published
where course.published
group by course.slug;

create or replace view public.academy_quiz_questions_public as
select
  question.id,
  question.lesson_slug,
  question.prompt,
  question.options,
  question.display_order
from public.academy_quiz_questions question
join public.academy_lessons lesson on lesson.slug = question.lesson_slug
join public.academy_courses course on course.slug = lesson.course_slug
where lesson.published and course.published;

grant select on public.academy_catalog to anon, authenticated;
grant select on public.academy_quiz_questions_public to anon, authenticated;

create or replace function public.grade_academy_quiz(
  p_lesson_slug text,
  p_answers jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  question record;
  submitted_option integer;
  correct_count integer := 0;
  total_count integer := 0;
  score_value numeric(5,2) := 0;
  result_items jsonb := '[]'::jsonb;
  current_user uuid := auth.uid();
begin
  if jsonb_typeof(p_answers) <> 'object' then
    raise exception 'Quiz answers must be a JSON object';
  end if;

  if not exists (
    select 1
    from public.academy_lessons lesson
    join public.academy_courses course on course.slug = lesson.course_slug
    where lesson.slug = p_lesson_slug and lesson.published and course.published
  ) then
    raise exception 'Published lesson not found';
  end if;

  for question in
    select id, correct_option, explanation
    from public.academy_quiz_questions
    where lesson_slug = p_lesson_slug
    order by display_order
  loop
    total_count := total_count + 1;
    submitted_option := null;

    if p_answers ? question.id::text and (p_answers ->> question.id::text) ~ '^[0-9]+$' then
      submitted_option := (p_answers ->> question.id::text)::integer;
    end if;

    if submitted_option = question.correct_option then
      correct_count := correct_count + 1;
    end if;

    result_items := result_items || jsonb_build_array(jsonb_build_object(
      'questionId', question.id,
      'correct', submitted_option = question.correct_option,
      'correctOption', question.correct_option,
      'explanation', question.explanation
    ));
  end loop;

  if total_count = 0 then
    raise exception 'This lesson does not have a quiz';
  end if;

  score_value := round(correct_count::numeric / total_count * 100, 2);

  if current_user is not null then
    insert into public.academy_lesson_progress (
      user_id,
      lesson_slug,
      status,
      best_score,
      attempts,
      completed_at
    ) values (
      current_user,
      p_lesson_slug,
      case when score_value >= 70 then 'completed' else 'in_progress' end,
      score_value,
      1,
      case when score_value >= 70 then now() else null end
    )
    on conflict (user_id, lesson_slug) do update
    set
      status = case
        when academy_lesson_progress.status = 'completed' or score_value >= 70
          then 'completed'
        else 'in_progress'
      end,
      best_score = greatest(coalesce(academy_lesson_progress.best_score, 0), score_value),
      attempts = academy_lesson_progress.attempts + 1,
      completed_at = case
        when academy_lesson_progress.completed_at is not null
          then academy_lesson_progress.completed_at
        when score_value >= 70 then now()
        else null
      end,
      updated_at = now();
  end if;

  return jsonb_build_object(
    'lessonSlug', p_lesson_slug,
    'score', score_value,
    'passed', score_value >= 70,
    'correct', correct_count,
    'total', total_count,
    'results', result_items
  );
end;
$$;

revoke all on function public.grade_academy_quiz(text, jsonb) from public;
grant execute on function public.grade_academy_quiz(text, jsonb) to anon, authenticated;

