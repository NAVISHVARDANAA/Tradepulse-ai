alter table public.market_alerts
  drop constraint if exists market_alerts_condition_check;

alter table public.market_alerts
  alter column target_value drop not null,
  add column if not exists delivery_channels text[] not null default array['in_app']::text[],
  add column if not exists cooldown_minutes integer not null default 1440,
  add column if not exists last_evaluated_at timestamptz,
  add column if not exists last_evaluation_key text;

alter table public.market_alerts
  drop constraint if exists market_alerts_supported_condition,
  drop constraint if exists market_alerts_target_requirement,
  drop constraint if exists market_alerts_delivery_channels_check,
  drop constraint if exists market_alerts_cooldown_check;

alter table public.market_alerts
  add constraint market_alerts_supported_condition check (
    condition in (
      'price_above',
      'price_below',
      'change_above',
      'change_below',
      'research_score_above',
      'research_score_below',
      'classification_changed',
      'forecast_direction_changed',
      'risk_flags_changed'
    )
  ),
  add constraint market_alerts_target_requirement check (
    condition in (
      'classification_changed',
      'forecast_direction_changed',
      'risk_flags_changed'
    )
    or target_value is not null
  ),
  add constraint market_alerts_delivery_channels_check check (
    cardinality(delivery_channels) between 1 and 3
    and delivery_channels <@ array['in_app', 'email', 'push']::text[]
  ),
  add constraint market_alerts_cooldown_check check (
    cooldown_minutes between 5 and 43200
  );

create unique index if not exists idx_market_alerts_unique_enabled_rule
  on public.market_alerts (
    user_id,
    asset_id,
    condition,
    coalesce(target_value, -999999999::numeric)
  )
  where enabled;

create table if not exists public.research_brief_preferences (
  user_id uuid primary key references auth.users(id) on delete cascade,
  enabled boolean not null default true,
  cadence text not null default 'weekdays' check (
    cadence in ('daily', 'weekdays', 'weekly')
  ),
  timezone text not null default 'UTC' check (char_length(timezone) between 1 and 64),
  delivery_hour smallint not null default 7 check (delivery_hour between 0 and 23),
  billing_currency text not null default 'USD'
    references public.billing_currencies(code),
  include_positive boolean not null default true,
  include_cautious boolean not null default true,
  include_risk_digest boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.research_briefs (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  brief_date date not null,
  cadence text not null check (cadence in ('daily', 'weekdays', 'weekly', 'on_demand')),
  title text not null,
  executive_summary text not null,
  highlights jsonb not null default '[]'::jsonb,
  risk_digest jsonb not null default '[]'::jsonb,
  coverage_summary jsonb not null default '{}'::jsonb,
