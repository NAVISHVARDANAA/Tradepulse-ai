  content_hash text not null,
  source_max_timestamp timestamptz,
  generated_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  unique (user_id, brief_date, cadence)
);

create table if not exists public.research_alert_events (
  id bigint generated by default as identity primary key,
  alert_id bigint not null references public.market_alerts(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  asset_id bigint not null references public.market_assets(id) on delete cascade,
  triggered_at timestamptz not null default now(),
  event_type text not null,
  severity text not null default 'info' check (severity in ('info', 'warning', 'critical')),
  title text not null,
  message text not null,
  observed_value numeric(20,8),
  threshold_value numeric(20,8),
  evidence jsonb not null default '{}'::jsonb,
  delivery_status text not null default 'in_app' check (
    delivery_status in ('in_app', 'queued', 'sent', 'failed')
  ),
  deduplication_key text not null unique,
  read_at timestamptz,
  created_at timestamptz not null default now()
);

