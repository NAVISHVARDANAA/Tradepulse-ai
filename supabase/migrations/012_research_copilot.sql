insert into public.research_brief_preferences (user_id, billing_currency)
select profile.id, profile.preferred_billing_currency
from public.profiles profile
on conflict (user_id) do nothing;

create or replace function public.handle_research_profile_created()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.research_brief_preferences (user_id, billing_currency)
  values (new.id, new.preferred_billing_currency)
  on conflict (user_id) do nothing;

  return new;
end;
$$;

drop trigger if exists on_research_profile_created on public.profiles;
create trigger on_research_profile_created
  after insert on public.profiles
  for each row execute function public.handle_research_profile_created();

create or replace view public.user_equity_watchlist_dashboard
with (security_invoker = true)
as
select
  watchlist.user_id,
  watchlist.id as watchlist_id,
  watchlist.name as watchlist_name,
  watchlist.is_default,
  item.id as watchlist_item_id,
  item.created_at as added_at,
  research.*
from public.watchlists watchlist
join public.watchlist_items item
  on item.watchlist_id = watchlist.id
join public.equity_research_dashboard research
  on research.market_asset_id = item.asset_id
where watchlist.user_id = auth.uid();

grant select on public.user_equity_watchlist_dashboard to authenticated;

do $$
begin
  if exists (
    select 1 from pg_publication where pubname = 'supabase_realtime'
  ) then
    if not exists (
      select 1 from pg_publication_tables
      where pubname = 'supabase_realtime'
        and schemaname = 'public'
        and tablename = 'research_briefs'
    ) then
      execute 'alter publication supabase_realtime add table public.research_briefs';
    end if;

    if not exists (
      select 1 from pg_publication_tables
      where pubname = 'supabase_realtime'
        and schemaname = 'public'
        and tablename = 'research_alert_events'
    ) then
      execute 'alter publication supabase_realtime add table public.research_alert_events';
    end if;
  end if;
end;
$$;

