create view public.global_evidence_review_queue_catalog with (security_invoker=true) as
select review_case.id, review_case.case_key, review_case.claim_class,
  policy.display_name claim_class_name, review_case.country_scope,
  review_case.rehearsal_summary, review_case.independent_source_count,
  policy.minimum_independent_sources required_independent_sources,
  review_case.primary_source_count, policy.minimum_primary_sources required_primary_sources,
  review_case.rights_status, review_case.authenticity_status,
  review_case.corroboration_status, review_case.conflict_status,
  review_case.review_status, review_case.synthetic, review_case.display_eligible,
  review_case.publication_eligible, review_case.model_eligible,
  review_case.observed_at,
  (select count(*) from public.global_evidence_review_stages stage
    where stage.review_case_id = review_case.id)::integer stage_count,
  (select count(*) from public.global_evidence_review_stages stage
    where stage.review_case_id = review_case.id and stage.stage_status = 'evidence_missing')::integer blocking_stage_count
from public.global_evidence_review_cases review_case
join public.global_evidence_corroboration_policies policy
  on policy.claim_class = review_case.claim_class;

create view public.global_evidence_review_stage_catalog with (security_invoker=true) as
select stage.id, stage.review_case_id, review_case.case_key,
  stage.sequence_number, stage.stage_key, stage.stage_status,
  stage.requirement_note, stage.human_review_required, stage.production_effect
from public.global_evidence_review_stages stage
join public.global_evidence_review_cases review_case on review_case.id = stage.review_case_id;

