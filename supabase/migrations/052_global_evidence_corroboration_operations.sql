create view public.global_evidence_operations_status with (security_invoker=true) as
select control.*,
  (select count(*) from public.global_evidence_source_lanes)::integer source_lane_count,
  (select count(*) from public.global_evidence_source_lanes where ingestion_enabled)::integer enabled_source_lane_count,
  (select count(*) from public.global_evidence_corroboration_policies)::integer corroboration_policy_count,
  (select count(*) from public.global_evidence_review_cases)::integer rehearsal_case_count,
  (select count(*) from public.global_evidence_review_cases where publication_eligible)::integer publication_eligible_case_count
from public.global_evidence_operations_controls control;

