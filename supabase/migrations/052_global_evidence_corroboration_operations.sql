from public.global_evidence_review_cases review_case
cross join (values
  (1, 'source_rights', 'Verify access, storage, display, derivation and model-use rights for every exact source.'),
  (2, 'source_authenticity', 'Verify publisher identity, endpoint ownership, signatures and immutable provenance.'),
  (3, 'extraction_integrity', 'Reconcile normalized fields to the licensed source without storing prohibited raw content.'),
  (4, 'temporal_alignment', 'Prove publication, observation and processing times obey the no-future-data boundary.'),
  (5, 'independent_corroboration', 'Meet the claim-specific independent and primary-source thresholds.'),
  (6, 'conflict_resolution', 'Hold or reject conflicting material claims until a human resolves the evidence.'),
  (7, 'editorial_approval', 'Require an accountable human decision before customer-visible publication.'),
  (8, 'model_eligibility', 'Evaluate licensing, leakage, quality and bias separately before any training use.')
) as stage(sequence_number, stage_key, requirement_note);

