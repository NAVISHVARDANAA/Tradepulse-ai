create table public.global_evidence_review_stages (
  id bigint generated by default as identity primary key,
  review_case_id bigint not null references public.global_evidence_review_cases(id) on delete cascade,
  sequence_number smallint not null check (sequence_number between 1 and 8),
  stage_key text not null check (stage_key in (
    'source_rights', 'source_authenticity', 'extraction_integrity',
    'temporal_alignment', 'independent_corroboration', 'conflict_resolution',
    'editorial_approval', 'model_eligibility'
  )),
  stage_status text not null default 'evidence_missing' check (stage_status = 'evidence_missing'),
  requirement_note text not null check (char_length(requirement_note) between 20 and 300),
  human_review_required boolean not null default true check (human_review_required),
  production_effect boolean not null default false check (not production_effect),
  created_at timestamptz not null default now(),
  unique (review_case_id, stage_key),
  unique (review_case_id, sequence_number)
);

