-- Migration 015: Broker sandbox certification control plane
-- Certification evidence is sandbox-only and cannot enable or route live orders.

create table if not exists public.broker_certification_test_catalog (
  code text primary key check (code ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  adapter_contract_version text not null,
  category text not null check (
    category in ('security', 'accounts', 'orders', 'webhooks', 'resilience', 'reconciliation')
  ),
  title text not null,
  description text not null,
  required boolean not null default true,
  sequence integer not null check (sequence > 0),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (adapter_contract_version, sequence)
);

create table if not exists public.broker_certification_runs (
  id uuid primary key default gen_random_uuid(),
  provider_id bigint not null references public.broker_provider_registry(id),
  environment text not null default 'sandbox' check (environment = 'sandbox'),
  adapter_contract_version text not null,
  suite_version text not null,
  source_commit_sha text not null check (source_commit_sha ~ '^[0-9a-f]{7,40}$'),
  status text not null check (status in ('passed', 'failed')),
  required_tests integer not null check (required_tests > 0),
  passed_tests integer not null check (passed_tests >= 0),
  failed_tests integer not null check (failed_tests >= 0),
  live_order_routing_tested boolean not null default false check (not live_order_routing_tested),
  evidence_digest text check (evidence_digest is null or evidence_digest ~ '^[0-9a-f]{64}$'),
  started_at timestamptz not null,
  completed_at timestamptz not null,
  created_at timestamptz not null default now(),
  check (completed_at >= started_at),
  check (passed_tests + failed_tests >= required_tests),
  check (status <> 'passed' or failed_tests = 0)
);

create table if not exists public.broker_certification_results (
  id bigint generated by default as identity primary key,
  run_id uuid not null references public.broker_certification_runs(id) on delete cascade,
  test_code text not null references public.broker_certification_test_catalog(code),
  status text not null check (status in ('passed', 'failed')),
  latency_ms integer check (latency_ms is null or latency_ms >= 0),
  attempt_count integer not null default 1 check (attempt_count > 0),
  error_code text check (
    error_code is null or error_code ~ '^[A-Z0-9]+(?:_[A-Z0-9]+)*$'
  ),
  evidence_digest text check (evidence_digest is null or evidence_digest ~ '^[0-9a-f]{64}$'),
  created_at timestamptz not null default now(),
  unique (run_id, test_code),
  check (status <> 'passed' or error_code is null)
);

create index if not exists idx_broker_certification_runs_provider_completed
  on public.broker_certification_runs(provider_id, completed_at desc);

create index if not exists idx_broker_certification_results_run_status
  on public.broker_certification_results(run_id, status);

alter table public.broker_certification_test_catalog enable row level security;
alter table public.broker_certification_runs enable row level security;
alter table public.broker_certification_results enable row level security;

create policy "Public reads broker certification catalog"
  on public.broker_certification_test_catalog for select to anon, authenticated
  using (active);

create policy "Public reads sanitized broker certification runs"
  on public.broker_certification_runs for select to anon, authenticated
  using (true);

create policy "Public reads sanitized broker certification results"
  on public.broker_certification_results for select to anon, authenticated
  using (true);

revoke insert, update, delete on public.broker_certification_test_catalog from anon, authenticated;
revoke insert, update, delete on public.broker_certification_runs from anon, authenticated;
revoke insert, update, delete on public.broker_certification_results from anon, authenticated;
revoke update, delete on public.broker_certification_runs from service_role;
revoke update, delete on public.broker_certification_results from service_role;

create or replace function public.prevent_broker_certification_mutation()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  raise exception 'Broker certification evidence is append-only';
end;
$$;

revoke all on function public.prevent_broker_certification_mutation() from public;

create trigger broker_certification_runs_append_only
  before update or delete on public.broker_certification_runs
  for each row execute function public.prevent_broker_certification_mutation();

create trigger broker_certification_results_append_only
  before update or delete on public.broker_certification_results
  for each row execute function public.prevent_broker_certification_mutation();

