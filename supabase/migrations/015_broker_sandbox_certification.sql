create or replace function public.persist_broker_certification_report(
  p_provider_code text,
  p_suite_version text,
  p_source_commit_sha text,
  p_started_at timestamptz,
  p_completed_at timestamptz,
  p_results jsonb,
  p_evidence_digest text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  provider_record public.broker_provider_registry%rowtype;
  run_record public.broker_certification_runs%rowtype;
  required_count integer;
  passed_count integer;
  failed_count integer;
  overall_status text;
begin
  if auth.role() <> 'service_role' then
    raise exception 'This operation requires the broker-certification service';
  end if;

  select * into provider_record
  from public.broker_provider_registry
  where code = p_provider_code;

  if provider_record.id is null then
    raise exception 'Broker provider contract not found';
  end if;

  if provider_record.live_order_routing_enabled then
    raise exception 'Certification refuses providers with live routing enabled';
  end if;

  if exists (
    select 1
    from public.brokerage_execution_controls
    where control_key = 'global-live-orders'
      and execution_enabled
  ) then
    raise exception 'Certification requires the global live-order lock';
  end if;

  if jsonb_typeof(p_results) <> 'array' or jsonb_array_length(p_results) = 0 then
    raise exception 'Certification results must be a non-empty array';
  end if;

  if exists (
    select 1
    from jsonb_array_elements(p_results) item
    where case
      when jsonb_typeof(item) <> 'object' then true
      else
        (item ->> 'code') is null
        or (item ->> 'status') is null
        or (item ->> 'status') not in ('passed', 'failed')
        or exists (
          select 1
          from jsonb_object_keys(item) key
          where key not in ('code', 'status', 'latencyMs', 'attemptCount', 'errorCode', 'evidenceDigest')
        )
    end
  ) then
    raise exception 'Certification result shape is invalid';
  end if;

  if (
    select count(*) <> count(distinct item ->> 'code')
    from jsonb_array_elements(p_results) item
  ) then
    raise exception 'Certification test codes must be unique';
  end if;

  if exists (
    select 1
    from jsonb_array_elements(p_results) item
    left join public.broker_certification_test_catalog test
      on test.code = item ->> 'code'
     and test.adapter_contract_version = provider_record.adapter_contract_version
     and test.active
    where test.code is null
  ) then
    raise exception 'Certification report contains an unknown or inactive test';
  end if;

  if exists (
    select 1
    from public.broker_certification_test_catalog test
    where test.adapter_contract_version = provider_record.adapter_contract_version
      and test.active
      and test.required
      and not exists (
        select 1
        from jsonb_array_elements(p_results) item
        where item ->> 'code' = test.code
      )
  ) then
    raise exception 'Certification report is missing a required test';
  end if;

  select count(*) into required_count
  from public.broker_certification_test_catalog
  where adapter_contract_version = provider_record.adapter_contract_version
    and active
    and required;

  select
    count(*) filter (where item ->> 'status' = 'passed'),
    count(*) filter (where item ->> 'status' = 'failed')
  into passed_count, failed_count
  from jsonb_array_elements(p_results) item;

  overall_status := case when failed_count = 0 then 'passed' else 'failed' end;

  insert into public.broker_certification_runs (
    provider_id,
    environment,
    adapter_contract_version,
    suite_version,
    source_commit_sha,
    status,
    required_tests,
    passed_tests,
    failed_tests,
    live_order_routing_tested,
    evidence_digest,
    started_at,
    completed_at
  ) values (
    provider_record.id,
    'sandbox',
    provider_record.adapter_contract_version,
    p_suite_version,
    p_source_commit_sha,
    overall_status,
    required_count,
    passed_count,
    failed_count,
    false,
    p_evidence_digest,
    p_started_at,
    p_completed_at
  ) returning * into run_record;

  insert into public.broker_certification_results (
    run_id,
    test_code,
    status,
    latency_ms,
    attempt_count,
    error_code,
    evidence_digest
  )
  select
    run_record.id,
    item ->> 'code',
    item ->> 'status',
    case when item ? 'latencyMs' then (item ->> 'latencyMs')::integer else null end,
    coalesce((item ->> 'attemptCount')::integer, 1),
    nullif(item ->> 'errorCode', ''),
    nullif(item ->> 'evidenceDigest', '')
  from jsonb_array_elements(p_results) item;

  insert into public.financial_audit_events (
    event_type,
    resource_type,
    resource_id,
    actor_type,
    correlation_id,
    details
  ) values (
    'broker_sandbox_certification_recorded',
    'broker_certification_run',
    run_record.id::text,
    'system',
    p_source_commit_sha,
    jsonb_build_object(
      'providerCode', provider_record.code,
      'environment', 'sandbox',
      'status', overall_status,
      'passedTests', passed_count,
      'failedTests', failed_count,
      'liveOrderRoutingTested', false
    )
  );

  return jsonb_build_object(
    'id', run_record.id,
    'providerCode', provider_record.code,
    'environment', run_record.environment,
    'status', run_record.status,
    'passedTests', run_record.passed_tests,
    'failedTests', run_record.failed_tests,
    'completedAt', run_record.completed_at,
    'liveOrderRoutingTested', false
  );
end;
$$;

