create or replace view public.broker_certification_readiness
with (security_invoker = true)
as
select
  provider.id as provider_id,
  provider.code as provider_code,
  provider.display_name,
  provider.adapter_contract_version,
  provider.regulatory_status,
  provider.integration_status,
  provider.live_order_routing_enabled,
  catalog.required_tests,
  latest.id as latest_run_id,
  latest.status as latest_status,
  latest.suite_version,
  latest.source_commit_sha,
  latest.passed_tests,
  latest.failed_tests,
  latest.completed_at,
  latest.live_order_routing_tested
from public.broker_provider_registry provider
join lateral (
  select count(*)::integer as required_tests
  from public.broker_certification_test_catalog test
  where test.adapter_contract_version = provider.adapter_contract_version
    and test.active
    and test.required
) catalog on true
left join lateral (
  select run.*
  from public.broker_certification_runs run
  where run.provider_id = provider.id
  order by run.completed_at desc, run.created_at desc
  limit 1
) latest on true;

create or replace view public.broker_certification_latest_results
with (security_invoker = true)
as
select
  provider.id as provider_id,
  provider.code as provider_code,
  test.code as test_code,
  test.category,
  test.title,
  test.description,
  test.required,
  test.sequence,
  latest.id as latest_run_id,
  coalesce(result.status, 'not_run') as status,
  result.latency_ms,
  result.attempt_count,
  result.error_code,
  latest.completed_at
from public.broker_provider_registry provider
join public.broker_certification_test_catalog test
  on test.adapter_contract_version = provider.adapter_contract_version
 and test.active
left join lateral (
  select run.*
  from public.broker_certification_runs run
  where run.provider_id = provider.id
  order by run.completed_at desc, run.created_at desc
  limit 1
) latest on true
left join public.broker_certification_results result
  on result.run_id = latest.id
 and result.test_code = test.code;

grant select on public.broker_certification_readiness to anon, authenticated;
grant select on public.broker_certification_latest_results to anon, authenticated;

