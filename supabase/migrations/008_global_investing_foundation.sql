create policy "Users can submit pending paper orders"
  on public.paper_orders for insert to authenticated
  with check (
    user_id = auth.uid()
    and status = 'pending'
    and execution_mode = 'paper'
    and exists (
      select 1
      from public.investment_portfolios
      where investment_portfolios.id = paper_orders.portfolio_id
        and investment_portfolios.user_id = auth.uid()
        and investment_portfolios.portfolio_type = 'paper'
    )
    and exists (
      select 1
      from public.investment_instruments
      where investment_instruments.id = paper_orders.instrument_id
        and investment_instruments.paper_trading_enabled
    )
  );

create policy "Users can read their paper fills"
  on public.paper_fills for select to authenticated
  using (
    exists (
      select 1
      from public.paper_orders
      where paper_orders.id = paper_fills.order_id
        and paper_orders.user_id = auth.uid()
    )
  );

