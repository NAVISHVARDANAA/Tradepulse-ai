create table if not exists public.jurisdictions (
  country_code text primary key references public.countries(iso_code),
  availability_status text not null default 'research_only' check (
    availability_status in (
      'research_only',
      'paper_trading',
      'execution_pending',
      'execution_enabled',
      'blocked'
    )
  ),
  retail_investing_enabled boolean not null default false,
  cross_border_payments_enabled boolean not null default false,
  legal_reviewed_at timestamptz,
  policy_version text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.investment_venues (
  id bigint generated by default as identity primary key,
  mic_code text not null unique,
  name text not null,
  country_code text not null references public.jurisdictions(country_code),
  venue_type text not null check (
    venue_type in ('exchange', 'broker', 'crypto_exchange', 'fund_platform')
  ),
  timezone text not null default 'UTC',
  execution_enabled boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.investment_instruments (
  id bigint generated by default as identity primary key,
  canonical_symbol text not null unique,
  display_symbol text not null,
  name text not null,
  asset_class text not null check (
    asset_class in (
      'equity',
      'etf',
      'bond',
      'fund',
      'forex',
      'commodity',
      'index',
      'crypto'
    )
  ),
  venue_id bigint references public.investment_venues(id),
  isin text,
  quote_currency text not null check (quote_currency ~ '^[A-Z]{3}$'),
  research_enabled boolean not null default true,
  paper_trading_enabled boolean not null default false,
  live_execution_enabled boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (not live_execution_enabled or venue_id is not null)
);

create table if not exists public.instrument_eligibility (
  instrument_id bigint not null references public.investment_instruments(id) on delete cascade,
  jurisdiction_code text not null references public.jurisdictions(country_code),
  investor_type text not null default 'retail' check (
    investor_type in ('retail', 'professional', 'accredited', 'institutional')
  ),
  availability text not null default 'review_required' check (
    availability in ('allowed', 'restricted', 'blocked', 'review_required')
  ),
  reason_code text,
  effective_from timestamptz not null default now(),
  effective_until timestamptz,
  policy_version text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (instrument_id, jurisdiction_code, investor_type),
  check (effective_until is null or effective_until > effective_from)
);

create table if not exists public.user_investor_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  declared_residency_country text references public.jurisdictions(country_code),
  verified_residency_country text references public.jurisdictions(country_code),
  tax_residency_country text references public.jurisdictions(country_code),
  base_currency text not null default 'USD' check (base_currency ~ '^[A-Z]{3}$'),
  investor_type text not null default 'retail' check (
    investor_type in ('retail', 'professional', 'accredited', 'institutional')
  ),
  risk_tolerance text check (risk_tolerance in ('conservative', 'moderate', 'aggressive')),
  kyc_status text not null default 'not_started' check (
    kyc_status in ('not_started', 'pending', 'verified', 'rejected', 'expired')
  ),
  suitability_status text not null default 'not_assessed' check (
    suitability_status in ('not_assessed', 'pending', 'suitable', 'restricted')
  ),
  sanctions_status text not null default 'not_screened' check (
    sanctions_status in ('not_screened', 'clear', 'review', 'blocked')
  ),
  onboarding_state text not null default 'research_only' check (
    onboarding_state in ('research_only', 'paper_ready', 'execution_review', 'execution_ready', 'blocked')
  ),
  compliance_reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.investment_portfolios (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  base_currency text not null default 'USD' check (base_currency ~ '^[A-Z]{3}$'),
  portfolio_type text not null default 'paper' check (portfolio_type = 'paper'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, name)
);

create table if not exists public.paper_orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  portfolio_id uuid not null references public.investment_portfolios(id) on delete cascade,
  instrument_id bigint not null references public.investment_instruments(id),
  client_order_id text not null,
  side text not null check (side in ('buy', 'sell')),
  order_type text not null check (order_type in ('market', 'limit', 'stop', 'stop_limit')),
  time_in_force text not null default 'day' check (time_in_force in ('day', 'gtc', 'ioc')),
  quantity numeric(24,8) not null check (quantity > 0),
  limit_price numeric(20,8) check (limit_price is null or limit_price > 0),
  stop_price numeric(20,8) check (stop_price is null or stop_price > 0),
  status text not null default 'pending' check (
    status in ('pending', 'risk_rejected', 'accepted', 'partially_filled', 'filled', 'cancelled')
  ),
  execution_mode text not null default 'paper' check (execution_mode = 'paper'),
  submitted_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, client_order_id),
  check (order_type not in ('limit', 'stop_limit') or limit_price is not null),
  check (order_type not in ('stop', 'stop_limit') or stop_price is not null)
);

create table if not exists public.paper_fills (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.paper_orders(id) on delete cascade,
  quantity numeric(24,8) not null check (quantity > 0),
  price numeric(20,8) not null check (price > 0),
  fee numeric(20,8) not null default 0 check (fee >= 0),
  filled_at timestamptz not null default now()
);

create table if not exists public.paper_positions (
  id uuid primary key default gen_random_uuid(),
  portfolio_id uuid not null references public.investment_portfolios(id) on delete cascade,
  instrument_id bigint not null references public.investment_instruments(id),
  quantity numeric(24,8) not null default 0,
  average_cost numeric(20,8) not null default 0 check (average_cost >= 0),
  realized_pnl numeric(20,8) not null default 0,
  updated_at timestamptz not null default now(),
  unique (portfolio_id, instrument_id)
);

create table if not exists public.order_risk_checks (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.paper_orders(id) on delete cascade,
