join public.global_event_entities from_entity on from_entity.id = edge.from_entity_id
join public.global_event_entities to_entity on to_entity.id = edge.to_entity_id
left join public.countries country on country.id = event.origin_country_id
left join public.market_assets asset on asset.id = edge.target_asset_id
where event.display_eligible and event.expires_at > now() and source.enabled;

create view public.global_country_intelligence_coverage
with (security_invoker = true)
as
select country.iso_code as country_code, country.name as country_name,
  country.region, profile.coverage_status, profile.monitored_event_types,
  profile.approved_source_count, profile.provider_coverage_enabled,
  count(event.id)::integer as current_event_count,
  max(event.source_published_at) as latest_event_at,
  case
    when count(event.id) = 0 then 'catalogued_no_current_event'
    when bool_and(event.synthetic) then 'synthetic_scenario_only'
    else 'evidence_available'
  end as evidence_state,
  profile.last_evaluated_at, profile.profile_version
from public.global_country_intelligence_profiles profile
join public.countries country on country.id = profile.country_id
left join public.global_event_records event
  on event.origin_country_id = country.id
  and event.display_eligible and event.expires_at > now()
  and exists (
    select 1 from public.global_event_source_registry source
    where source.id = event.source_id and source.enabled
  )
group by country.iso_code, country.name, country.region,
  profile.coverage_status, profile.monitored_event_types,
  profile.approved_source_count, profile.provider_coverage_enabled,
  profile.last_evaluated_at, profile.profile_version;

