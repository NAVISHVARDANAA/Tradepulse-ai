  rationale text not null check (char_length(rationale) between 20 and 500),
  assumptions jsonb not null default '[]'::jsonb check (jsonb_typeof(assumptions) = 'array'),
  target_asset_id bigint references public.market_assets(id),
  estimated_effect_low_pct numeric(8,4),
  estimated_effect_high_pct numeric(8,4),
