create or replace function public.save_global_event_alert_policy(
  p_client_policy_id text,
  p_name text,
  p_country_codes text[],
  p_event_types text[],
  p_asset_symbols text[],
  p_minimum_authenticity_score numeric,
  p_minimum_confidence_score numeric,
  p_minimum_severity text
)
returns public.user_global_event_alert_policies
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_policy public.user_global_event_alert_policies;
begin
  if v_user_id is null then
    raise exception 'Authentication required';
  end if;
  if p_client_policy_id !~ '^[A-Za-z0-9:_-]{8,100}$'
    or char_length(trim(p_name)) not between 3 and 80
    or cardinality(p_country_codes) not between 1 and 12
    or cardinality(p_event_types) not between 1 and 10
    or cardinality(p_asset_symbols) not between 0 and 12
    or p_minimum_authenticity_score not between 0 and 1
    or p_minimum_confidence_score not between 0 and 1
    or p_minimum_severity not in ('low', 'medium', 'high', 'critical') then
    raise exception 'Invalid global event alert policy';
  end if;
  if exists (
    select 1 from unnest(p_country_codes) code
    where code <> 'GLOBAL' and not exists (
      select 1 from public.countries country where country.iso_code = code
    )
  ) then
    raise exception 'Unsupported country code';
  end if;
  if exists (
    select 1 from unnest(p_event_types) event_type
    where event_type not in (
      'resource_discovery', 'energy_supply', 'logistics_disruption',
      'monetary_policy', 'geopolitics', 'extreme_weather', 'macro_data',
      'regulation', 'infrastructure', 'technology'
    )
  ) then
    raise exception 'Unsupported event type';
  end if;
  if exists (
    select 1 from unnest(p_asset_symbols) symbol
    where not exists (select 1 from public.market_assets asset where asset.symbol = symbol)
  ) then
    raise exception 'Unsupported market asset';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('global-event-alert-user:' || v_user_id::text, 0)
  );
  if not exists (
    select 1 from public.user_global_event_alert_policies
    where user_id = v_user_id and client_policy_id = p_client_policy_id and active
  ) and (
    select count(*) from public.user_global_event_alert_policies
    where user_id = v_user_id and active
  ) >= 12 then
    raise exception 'Global event alert policy limit reached';
  end if;

  insert into public.user_global_event_alert_policies (
    user_id, client_policy_id, name, country_codes, event_types,
    asset_symbols, minimum_authenticity_score, minimum_confidence_score,
    minimum_severity
  ) values (
    v_user_id, p_client_policy_id, trim(p_name), p_country_codes, p_event_types,
    p_asset_symbols, p_minimum_authenticity_score, p_minimum_confidence_score,
    p_minimum_severity
  )
  on conflict (user_id, client_policy_id) do update set
    name = excluded.name, country_codes = excluded.country_codes,
    event_types = excluded.event_types, asset_symbols = excluded.asset_symbols,
    minimum_authenticity_score = excluded.minimum_authenticity_score,
    minimum_confidence_score = excluded.minimum_confidence_score,
    minimum_severity = excluded.minimum_severity, active = true
  returning * into v_policy;
  return v_policy;
end;
$$;

revoke all on function public.save_global_event_alert_policy(text, text, text[], text[], text[], numeric, numeric, text)
