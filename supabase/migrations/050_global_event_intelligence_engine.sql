  check (estimated_effect_low_pct is null or estimated_effect_high_pct is not null),
  check (estimated_effect_high_pct is null or estimated_effect_low_pct is not null),
  check (estimated_effect_low_pct is null or estimated_effect_low_pct <= estimated_effect_high_pct),
  check (not terminal_edge or target_asset_id is not null),
  check (not synthetic or not model_eligible)
