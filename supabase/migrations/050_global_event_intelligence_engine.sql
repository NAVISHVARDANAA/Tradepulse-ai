  event.event_type, event.normalized_summary as event_summary,
  country.iso_code as origin_country_code, event.region_code,
  edge.sequence_number, from_entity.entity_kind as from_entity_kind,
  from_entity.entity_key, from_entity.display_name as from_entity_name,
