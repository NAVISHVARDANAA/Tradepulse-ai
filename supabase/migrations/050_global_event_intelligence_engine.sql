create table public.global_event_records (
  id bigint generated by default as identity primary key,
  event_key text not null unique,
  source_id bigint not null references public.global_event_source_registry(id),
  origin_country_id bigint references public.countries(id),
  region_code text not null check (region_code ~ '^[A-Z]{2,12}$'),
  event_type text not null check (event_type in (
    'resource_discovery', 'energy_supply', 'logistics_disruption',
    'monetary_policy', 'geopolitics', 'extreme_weather', 'macro_data',
    'regulation', 'infrastructure', 'technology'
  )),
  normalized_summary text not null check (char_length(normalized_summary) between 20 and 500),
  source_reference text not null check (char_length(source_reference) between 8 and 240),
  input_digest text not null check (input_digest ~ '^[a-f0-9]{64}$'),
  source_published_at timestamptz not null,
  observed_at timestamptz not null default now(),
  expires_at timestamptz not null,
  authenticity_score numeric(6,5) not null check (authenticity_score between 0 and 1),
  corroboration_count integer not null default 0 check (corroboration_count between 0 and 20),
  verification_status text not null check (verification_status in ('synthetic', 'unverified', 'corroborated', 'verified', 'rejected')),
  severity text not null check (severity in ('low', 'medium', 'high', 'critical')),
  novelty_score numeric(6,5) not null check (novelty_score between 0 and 1),
  display_eligible boolean not null default false,
  model_eligible boolean not null default false,
  synthetic boolean not null default true,
  created_at timestamptz not null default now(),
  check (source_published_at <= observed_at),
  check (expires_at > observed_at),
  check (not synthetic or (verification_status = 'synthetic' and not model_eligible)),
  check (not display_eligible or verification_status in ('synthetic', 'corroborated', 'verified')),
  check (verification_status <> 'verified' or (not synthetic and corroboration_count >= 2 and authenticity_score >= 0.7)),
  check (not model_eligible or (
    not synthetic and verification_status in ('corroborated', 'verified')
      and corroboration_count >= 2 and authenticity_score >= 0.7
  ))
);

