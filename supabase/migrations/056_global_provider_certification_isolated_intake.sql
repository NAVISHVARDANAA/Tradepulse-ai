create view public.global_provider_certification_status with (security_invoker=true) as
select control.*,
  (select count(*) from public.global_provider_certification_profiles)::integer source_family_count,
  (select count(*) from public.global_provider_certification_profiles where certification_status = 'provider_unselected')::integer unselected_provider_count,
  (select count(*) from public.global_provider_certification_profiles where certification_approved)::integer certified_provider_count,
  (select count(*) from public.global_provider_certification_gate_templates)::integer certification_gate_count,
  (select count(*) from public.global_isolated_intake_profiles)::integer isolation_profile_count,
  (select count(*) from public.global_isolated_intake_profiles where environment_status = 'not_provisioned')::integer unprovisioned_isolation_count,
  (select count(*) from public.global_provider_failure_drill_templates)::integer failure_drill_count,
  (select coalesce(sum(observed_drill_count),0) from public.global_provider_failure_drill_templates)::integer observed_drill_count
from public.global_provider_certification_controls control;

create view public.global_provider_certification_catalog with (security_invoker=true) as
select profile.id, profile.sequence_number, profile.source_family_key,
  source.display_name source_family_name, source.source_class,
  profile.certification_status, profile.rights_review_status,
  profile.privacy_security_review_status, profile.schema_review_status,
  profile.provenance_review_status, profile.resilience_review_status,
  profile.accountable_owner_assigned, profile.certification_approved,
  profile.isolated_intake_approved, profile.production_effect, profile.gap_reason
from public.global_provider_certification_profiles profile
join public.global_observation_source_connectors source on source.id = profile.source_connector_id;

create view public.global_provider_certification_gate_catalog with (security_invoker=true) as
