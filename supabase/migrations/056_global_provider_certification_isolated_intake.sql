create view public.global_isolated_intake_catalog with (security_invoker=true) as
select isolation.id, profile.sequence_number, profile.source_family_key,
  isolation.environment_status, isolation.network_egress_enabled,
  isolation.credential_access_enabled, isolation.payload_storage_enabled,
  isolation.candidate_write_enabled, isolation.maximum_candidate_rows,
