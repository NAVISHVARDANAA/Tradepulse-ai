  isolation.model_eligible, isolation.production_effect
from public.global_isolated_intake_profiles isolation
join public.global_provider_certification_profiles profile on profile.id = isolation.certification_profile_id;

create view public.global_provider_failure_drill_catalog with (security_invoker=true) as
select id, sequence_number, drill_key, display_name, drill_requirement,
  expected_safe_state, observed_drill_count, automatic_pass_enabled,
  manual_evidence_required, blocks_certification
