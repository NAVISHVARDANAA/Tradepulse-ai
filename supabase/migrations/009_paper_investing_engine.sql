-- TradePulse AI
-- Migration 009: Transactional paper-investing engine
-- All balances, orders and fills created here are simulations with no cash value.

alter table public.investment_instruments
  add column if not exists market_asset_id bigint unique
    references public.market_assets(id);

alter table public.paper_orders
  add column if not exists reference_price numeric(20,8),
  add column if not exists average_fill_price numeric(20,8),
  add column if not exists total_fees numeric(20,8) not null default 0
    check (total_fees >= 0);

create table if not exists public.paper_cash_balances (
  portfolio_id uuid not null references public.investment_portfolios(id) on delete cascade,
  currency text not null check (currency ~ '^[A-Z]{3}$'),
  balance numeric(24,8) not null default 0 check (balance >= 0),
  available_balance numeric(24,8) not null default 0 check (available_balance >= 0),
  updated_at timestamptz not null default now(),
  primary key (portfolio_id, currency),
  check (available_balance <= balance)
);

create table if not exists public.portfolio_risk_limits (
  portfolio_id uuid primary key references public.investment_portfolios(id) on delete cascade,
  max_order_notional numeric(24,8) not null default 10000 check (max_order_notional > 0),
  max_position_notional numeric(24,8) not null default 25000 check (max_position_notional > 0),
  daily_loss_limit numeric(24,8) not null default 5000 check (daily_loss_limit > 0),
  max_open_orders integer not null default 20 check (max_open_orders between 1 and 100),
  rule_version text not null default 'paper-risk-v1',
  updated_at timestamptz not null default now()
);

create table if not exists public.paper_ledger_entries (
  id bigint generated by default as identity primary key,
  portfolio_id uuid not null references public.investment_portfolios(id) on delete cascade,
  currency text not null check (currency ~ '^[A-Z]{3}$'),
  entry_type text not null check (
    entry_type in ('initial_credit', 'trade_debit', 'trade_credit', 'fee', 'adjustment')
  ),
  amount numeric(24,8) not null,
  balance_after numeric(24,8) not null check (balance_after >= 0),
  order_id uuid references public.paper_orders(id) on delete set null,
  correlation_id text not null,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.portfolio_nav_snapshots (
  id bigint generated by default as identity primary key,
  portfolio_id uuid not null references public.investment_portfolios(id) on delete cascade,
  observed_at timestamptz not null,
  cash_value numeric(24,8) not null,
  position_value numeric(24,8) not null,
  total_value numeric(24,8) not null,
  daily_pnl numeric(24,8),
  drawdown_percent numeric(12,8),
  source text not null default 'paper-engine',
  unique (portfolio_id, observed_at)
);

create index if not exists idx_paper_ledger_portfolio_created
  on public.paper_ledger_entries(portfolio_id, created_at desc);

create index if not exists idx_portfolio_nav_portfolio_observed
  on public.portfolio_nav_snapshots(portfolio_id, observed_at desc);

alter table public.paper_cash_balances enable row level security;
alter table public.portfolio_risk_limits enable row level security;
alter table public.paper_ledger_entries enable row level security;
alter table public.portfolio_nav_snapshots enable row level security;

