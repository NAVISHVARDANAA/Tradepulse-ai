create or replace function public.create_global_brokerage_order_preview(
  p_user_id uuid,
  p_onboarding_case_id uuid,
  p_client_preview_id text,
  p_listing_id bigint,
  p_side text,
  p_order_type text,
  p_quantity numeric,
  p_limit_price numeric
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_existing public.global_brokerage_order_previews%rowtype;
  v_case public.global_brokerage_onboarding_cases%rowtype;
  v_matrix public.global_brokerage_launch_matrix%rowtype;
  v_listing public.global_instrument_listings%rowtype;
  v_quote public.international_paper_quotes%rowtype;
  v_cost public.international_paper_cost_rules%rowtype;
  v_quote_fx public.international_paper_fx_rates%rowtype;
  v_base_fx public.international_paper_fx_rates%rowtype;
  v_preview_id uuid;
  v_price numeric(20,8);
  v_gross numeric(24,8);
  v_commission numeric(24,8);
  v_venue_fee numeric(24,8);
  v_tax numeric(24,8);
  v_fx numeric(24,10);
  v_total_base numeric(24,8);
begin
  if current_setting('request.jwt.claim.role', true) <> 'service_role' then
    raise exception 'Global brokerage previews require the orchestration service';
  end if;
  if char_length(coalesce(p_client_preview_id, '')) not between 8 and 100
    or p_side not in ('buy', 'sell') or p_order_type not in ('market', 'limit')
    or p_quantity <= 0 or p_quantity > 1000000
    or (p_order_type = 'limit' and (p_limit_price is null or p_limit_price <= 0))
    or (p_order_type = 'market' and p_limit_price is not null) then
    raise exception 'Invalid global brokerage preview';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(p_user_id::text || ':' || p_client_preview_id, 0)
  );
  select * into v_existing from public.global_brokerage_order_previews
  where user_id = p_user_id and client_preview_id = p_client_preview_id;
  if v_existing.id is not null then
    if v_existing.onboarding_case_id <> p_onboarding_case_id
      or v_existing.listing_id <> p_listing_id or v_existing.side <> p_side
      or v_existing.order_type <> p_order_type or v_existing.quantity <> p_quantity
      or v_existing.limit_price is distinct from p_limit_price then
      raise exception 'Global brokerage preview id was reused with different input';
    end if;
    return jsonb_build_object('status', 'blocked', 'previewId', v_existing.id,
      'executable', false, 'idempotentReplay', true);
  end if;

  select * into v_case from public.global_brokerage_onboarding_cases
  where id = p_onboarding_case_id and user_id = p_user_id for update;
  if v_case.id is null or v_case.expires_at <= now()
    or v_case.case_status <> 'review_only' or v_case.activation_status <> 'blocked' then
    raise exception 'Global brokerage onboarding case is unavailable';
  end if;
  select * into v_matrix from public.global_brokerage_launch_matrix
  where id = v_case.launch_matrix_id;
  select * into v_listing from public.global_instrument_listings where id = p_listing_id;
  if v_listing.id is null or v_listing.venue_id <> v_matrix.venue_id
    or v_listing.instrument_type <> v_matrix.asset_class
    or v_listing.listing_status <> 'reference_only' then
    raise exception 'Listing is outside the blocked launch matrix';
  end if;

  select * into v_quote from public.international_paper_quotes
  where listing_id = p_listing_id and source_type = 'deterministic_fixture'
    and simulation_only and quote_status = 'available_scenario';
  select * into v_cost from public.international_paper_cost_rules
  where venue_id = v_listing.venue_id and instrument_type = v_listing.instrument_type
    and enabled and simulation_only;
  select * into v_quote_fx from public.international_paper_fx_rates
  where currency_code = v_listing.quote_currency and simulation_only;
  select * into v_base_fx from public.international_paper_fx_rates
  where currency_code = v_case.base_currency and simulation_only;
  if v_quote.id is null or v_cost.id is null
    or v_quote_fx.currency_code is null or v_base_fx.currency_code is null then
    raise exception 'Deterministic preview inputs are unavailable';
  end if;

  v_price := case when p_order_type = 'limit' then p_limit_price else v_quote.scenario_price end;
  v_gross := round(v_price * p_quantity, 8);
  v_commission := round(greatest(v_cost.minimum_commission, v_gross * v_cost.commission_bps / 10000), 8);
  v_venue_fee := round(v_gross * v_cost.exchange_fee_bps / 10000, 8);
  v_tax := case when v_cost.cost_status = 'modeled_scenario'
    then round(v_gross * v_cost.tax_assumption_bps / 10000, 8) else null end;
  v_fx := round(v_quote_fx.usd_value_per_unit / v_base_fx.usd_value_per_unit, 10);
  v_total_base := case when v_tax is null then null
    when p_side = 'buy' then round((v_gross + v_commission + v_venue_fee + v_tax) * v_fx, 8)
    else round((v_gross - v_commission - v_venue_fee - v_tax) * v_fx, 8) end;
  if v_total_base is not null and v_total_base <= 0 then
    raise exception 'Deterministic preview costs exceed the scenario notional';
  end if;

  insert into public.global_brokerage_order_previews (
    user_id, onboarding_case_id, client_preview_id, listing_id,
    side, order_type, quantity, limit_price, scenario_price, gross_notional,
    quote_currency, fx_rate_to_base, base_currency, commission_amount,
    venue_fee_amount, estimated_tax_amount, tax_status, estimated_total_base,
    settlement_currency, route_evidence, block_reasons, policy_version, expires_at
  ) values (
    p_user_id, p_onboarding_case_id, p_client_preview_id, p_listing_id,
    p_side, p_order_type, p_quantity,
    case when p_order_type = 'limit' then p_limit_price else null end,
    v_price, v_gross, v_listing.quote_currency, v_fx, v_case.base_currency,
    v_commission, v_venue_fee, v_tax,
    case when v_tax is null then 'unavailable' else 'modeled_scenario' end,
    v_total_base, v_matrix.settlement_currency,
    jsonb_build_array(
      jsonb_build_object('role', 'broker', 'status', 'unassigned'),
      jsonb_build_object('role', 'exchange', 'status', 'unassigned'),
      jsonb_build_object('role', 'clearing', 'status', 'unassigned'),
      jsonb_build_object('role', 'custody', 'status', 'unassigned'),
      jsonb_build_object('role', 'market_data', 'status', 'unassigned')
    ),
    jsonb_build_array(
      jsonb_build_object('code', 'GLOBAL_ACTIVATION_BLOCKED', 'owner', 'tradepulse', 'message', 'The exact launch matrix has no activation decision.'),
      jsonb_build_object('code', 'PARTNERS_UNASSIGNED', 'owner', 'operations', 'Broker, clearing, custody and market-data roles are unassigned.'),
      jsonb_build_object('code', 'ONBOARDING_UNAPPROVED', 'owner', 'compliance', 'Rehearsal evidence never satisfies onboarding approval.'),
      jsonb_build_object('code', 'BUYING_POWER_UNAVAILABLE', 'owner', 'broker', 'No real brokerage cash or buying power exists.'),
      jsonb_build_object('code', 'PAYMENT_FUNDING_SEPARATE', 'owner', 'payments', 'A payment quote cannot become brokerage cash.')
    ),
    'global-brokerage-custody-v1', now() + interval '5 minutes'
  ) returning id into v_preview_id;

  return jsonb_build_object('status', 'blocked', 'previewId', v_preview_id,
    'executable', false, 'estimatedTotalBase', v_total_base,
    'idempotentReplay', false);
end;
$$;

create or replace function public.reconcile_global_brokerage_case(
  p_user_id uuid,
  p_onboarding_case_id uuid,
  p_client_reconciliation_id text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_existing public.global_brokerage_reconciliation_runs%rowtype;
  v_run_id uuid;
begin
  if current_setting('request.jwt.claim.role', true) <> 'service_role' then
    raise exception 'Global brokerage reconciliation requires the orchestration service';
  end if;
  if char_length(coalesce(p_client_reconciliation_id, '')) not between 8 and 100 then
    raise exception 'Invalid global brokerage reconciliation';
  end if;
  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(p_user_id::text || ':' || p_client_reconciliation_id, 0)
  );
  select * into v_existing from public.global_brokerage_reconciliation_runs
  where user_id = p_user_id and client_reconciliation_id = p_client_reconciliation_id;
  if v_existing.id is not null then
    if v_existing.onboarding_case_id <> p_onboarding_case_id then
      raise exception 'Global brokerage reconciliation id was reused with different input';
    end if;
    return jsonb_build_object('status', 'not_ready', 'reconciliationId', v_existing.id,
      'blockingDomains', 5, 'idempotentReplay', true);
  end if;
  if not exists (
    select 1 from public.global_brokerage_onboarding_cases
    where id = p_onboarding_case_id and user_id = p_user_id
      and case_status = 'review_only' and activation_status = 'blocked'
      and expires_at > now()
  ) then
    raise exception 'Global brokerage onboarding case is unavailable';
  end if;

  insert into public.global_brokerage_reconciliation_runs (
    user_id, onboarding_case_id, client_reconciliation_id,
    reconciliation_version
  ) values (
    p_user_id, p_onboarding_case_id, p_client_reconciliation_id,
    'global-brokerage-reconciliation-v1'
  ) returning id into v_run_id;

  insert into public.global_brokerage_reconciliation_items (
    reconciliation_run_id, domain, detail
  ) values
    (v_run_id, 'order', 'No signed broker order event is connected.'),
    (v_run_id, 'allocation', 'No signed allocation or clearing record is connected.'),
    (v_run_id, 'cash', 'No real brokerage cash ledger or buying-power source is connected.'),
    (v_run_id, 'custody', 'No custodian position or safeguarding statement is connected.'),
    (v_run_id, 'settlement', 'No clearing or settlement instruction source is connected.');

  return jsonb_build_object('status', 'not_ready', 'reconciliationId', v_run_id,
    'blockingDomains', 5, 'productionEffect', false, 'idempotentReplay', false);
end;
$$;

