create view public.global_brokerage_launch_matrix_catalog
with (security_invoker = true)
as
select matrix.id as launch_matrix_id, matrix.matrix_code,
  matrix.residency_country, matrix.execution_jurisdiction,
  matrix.customer_type, matrix.investor_type, matrix.account_type,
  matrix.asset_class, venue.mic_code, venue.venue_name,
  matrix.settlement_currency, matrix.matrix_status,
  matrix.legal_approval_status, matrix.compliance_approval_status,
  matrix.tax_approval_status, matrix.market_data_approval_status,
  matrix.broker_approval_status, matrix.custody_approval_status,
  matrix.security_approval_status, matrix.operations_approval_status,
  8::integer as approval_gap_count,
  5::integer as partner_gap_count,
  (select count(*)::integer from public.global_brokerage_onboarding_requirements) as onboarding_requirement_count,
  false as onboarding_supported, true as preview_rehearsal_supported,
  false as live_execution_enabled, false as broker_connectivity_enabled,
  false as custody_enabled, false as settlement_enabled,
  false as cross_border_funding_link_enabled,
  matrix.source_name, matrix.source_as_of, matrix.matrix_version
from public.global_brokerage_launch_matrix matrix
join public.global_market_venues venue on venue.id = matrix.venue_id;

