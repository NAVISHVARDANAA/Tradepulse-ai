  (select count(*)::integer from public.global_brokerage_launch_matrix where matrix_status = 'blocked') as blocked_matrix_count,
  (select count(*)::integer from public.global_brokerage_partner_roles) as partner_role_count,
  (select count(*)::integer from public.global_brokerage_partner_roles where assignment_status = 'unassigned') as unassigned_partner_role_count,
  (select count(*)::integer from public.global_brokerage_onboarding_requirements) as onboarding_requirement_count,
  control.activation_status, control.manual_activation_review_required,
  false as live_broker_connectivity_enabled, false as custody_accounts_enabled,
  false as real_cash_ledger_enabled, false as real_position_ledger_enabled,
  false as settlement_instructions_enabled, false as cross_border_funding_link_enabled,
  false as live_order_routing_enabled, false as automatic_activation_enabled
