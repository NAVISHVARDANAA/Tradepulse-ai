create or replace function public.initialize_global_brokerage_case(
  p_user_id uuid,
  p_client_case_id text,
  p_launch_matrix_id bigint,
  p_base_currency text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_existing public.global_brokerage_onboarding_cases%rowtype;
  v_case public.global_brokerage_onboarding_cases%rowtype;
begin
  if current_setting('request.jwt.claim.role', true) <> 'service_role' then
    raise exception 'Global brokerage cases require the orchestration service';
  end if;
  if char_length(coalesce(p_client_case_id, '')) not between 8 and 100
    or p_base_currency !~ '^[A-Z]{3}$' then
    raise exception 'Invalid global brokerage case';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(p_user_id::text || ':' || p_client_case_id, 0)
  );
  select * into v_existing from public.global_brokerage_onboarding_cases
  where user_id = p_user_id and client_case_id = p_client_case_id;
  if v_existing.id is not null then
    if v_existing.launch_matrix_id <> p_launch_matrix_id
      or v_existing.base_currency <> p_base_currency then
      raise exception 'Global brokerage case id was reused with different input';
    end if;
    return jsonb_build_object('status', 'review_only', 'caseId', v_existing.id,
      'activationStatus', 'blocked', 'idempotentReplay', true);
  end if;

  if not exists (
    select 1 from public.global_brokerage_launch_matrix
    where id = p_launch_matrix_id and matrix_status = 'blocked'
      and preview_rehearsal_supported and not onboarding_supported
      and not live_execution_enabled
  ) then
    raise exception 'Global brokerage launch matrix is unavailable';
  end if;
  if not exists (select 1 from public.international_paper_fx_rates where currency_code = p_base_currency) then
    raise exception 'Base currency scenario is unavailable';
  end if;

  insert into public.global_brokerage_onboarding_cases (
    user_id, client_case_id, launch_matrix_id, base_currency
  ) values (p_user_id, p_client_case_id, p_launch_matrix_id, p_base_currency)
  returning * into v_case;

  return jsonb_build_object('status', 'review_only', 'caseId', v_case.id,
    'activationStatus', 'blocked', 'idempotentReplay', false);
end;
$$;

