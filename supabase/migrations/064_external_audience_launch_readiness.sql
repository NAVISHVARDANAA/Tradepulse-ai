create or replace function public.prevent_external_audience_launch_reference_mutation()
returns trigger language plpgsql set search_path = '' as $$
begin
  raise exception 'External audience launch-readiness reference records are append-only';
end;
$$;
revoke all on function public.prevent_external_audience_launch_reference_mutation() from public, anon, authenticated, service_role;

create trigger external_audience_launch_controls_append_only before update or delete on public.external_audience_launch_controls
  for each row execute function public.prevent_external_audience_launch_reference_mutation();
create trigger external_audience_launch_states_append_only before update or delete on public.external_audience_launch_state_templates
  for each row execute function public.prevent_external_audience_launch_reference_mutation();
create trigger external_audience_launch_surfaces_append_only before update or delete on public.external_audience_launch_surface_templates
  for each row execute function public.prevent_external_audience_launch_reference_mutation();
create trigger external_audience_launch_gates_append_only before update or delete on public.external_audience_launch_gate_templates
  for each row execute function public.prevent_external_audience_launch_reference_mutation();
create trigger external_audience_launch_matrix_append_only before update or delete on public.external_audience_launch_readiness_matrix
  for each row execute function public.prevent_external_audience_launch_reference_mutation();

create view public.external_audience_launch_status with (security_invoker=true) as
select control.*,
  (select count(*) from public.external_audience_launch_surface_templates)::integer audience_surface_count,
  (select count(*) from public.external_audience_launch_gate_templates)::integer launch_gate_count,
  (select count(*) from public.external_audience_launch_state_templates)::integer launch_state_count,
  (select count(*) from public.external_audience_launch_readiness_matrix)::integer readiness_cell_count,
  (select count(*) from public.external_audience_launch_readiness_matrix where readiness_status = 'blocked')::integer blocked_readiness_cell_count,
  (select count(*) from public.external_audience_launch_readiness_matrix where human_authorized)::integer authorized_readiness_cell_count
from public.external_audience_launch_controls control;

create view public.external_audience_launch_state_catalog with (security_invoker=true) as
select id, sequence_number, state_key, display_name, state_definition,
  real_audience_present, automatic_transition_enabled, human_launch_authorization_required,
  public_access_effect, customer_data_effect, financial_execution_effect, production_effect
from public.external_audience_launch_state_templates;

create view public.external_audience_launch_surface_catalog with (security_invoker=true) as
select id, sequence_number, surface_key, display_name, surface_definition,
  audience_access_status, real_audience_present, customer_data_enabled,
  financial_execution_enabled, production_effect
from public.external_audience_launch_surface_templates;

create view public.external_audience_launch_gate_catalog with (security_invoker=true) as
select id, sequence_number, gate_key, launch_domain, display_name, gate_definition,
  gate_status, real_evidence_present, reviewer_assigned, human_authorized
from public.external_audience_launch_gate_templates;

create view public.external_audience_launch_readiness_catalog with (security_invoker=true) as
select matrix.id, surface.surface_key, surface.sequence_number surface_sequence_number,
  surface.display_name surface_name, gate.gate_key, gate.sequence_number gate_sequence_number,
  gate.display_name gate_name, gate.launch_domain, matrix.readiness_status,
  matrix.human_authorized, matrix.public_access_effect, matrix.account_provisioning_effect,
  matrix.customer_data_effect, matrix.live_provider_effect, matrix.publication_effect,
  matrix.financial_execution_effect, matrix.release_effect, matrix.production_effect
from public.external_audience_launch_readiness_matrix matrix
join public.external_audience_launch_surface_templates surface on surface.id = matrix.surface_template_id
join public.external_audience_launch_gate_templates gate on gate.id = matrix.gate_template_id;

grant select on public.external_audience_launch_status,
  public.external_audience_launch_state_catalog,
  public.external_audience_launch_surface_catalog,
  public.external_audience_launch_gate_catalog,
  public.external_audience_launch_readiness_catalog to anon, authenticated, service_role;

do $$
begin
  if (select count(*) from public.external_audience_launch_state_templates) <> 7
    or (select count(*) from public.external_audience_launch_surface_templates) <> 8
    or (select count(*) from public.external_audience_launch_gate_templates) <> 8
    or (select count(*) from public.external_audience_launch_readiness_matrix) <> 64 then
    raise exception 'Phase 8U external audience launch-readiness reference counts changed';
  end if;
  if exists (
    select 1 from public.external_audience_launch_controls
    where public_signup_enabled or unrestricted_discovery_enabled
      or automated_tester_provisioning_enabled or external_audience_activation_enabled
      or live_provider_connectivity_enabled or production_credential_storage_enabled
      or production_payload_intake_enabled or unrestricted_customer_data_collection_enabled
      or autonomous_publication_enabled or model_training_enabled or live_order_routing_enabled
      or payment_execution_enabled or money_movement_enabled or custody_enabled or settlement_enabled
  ) or exists (
    select 1 from public.external_audience_launch_state_templates
    where real_audience_present or automatic_transition_enabled
      or not human_launch_authorization_required or public_access_effect
      or customer_data_effect or financial_execution_effect or production_effect
  ) or exists (
    select 1 from public.external_audience_launch_surface_templates
    where audience_access_status <> 'unavailable' or real_audience_present
      or customer_data_enabled or financial_execution_enabled or production_effect
  ) or exists (
    select 1 from public.external_audience_launch_gate_templates
    where gate_status <> 'unmet' or real_evidence_present or reviewer_assigned or human_authorized
  ) or exists (
    select 1 from public.external_audience_launch_readiness_matrix
    where readiness_status <> 'blocked' or evidence_reference is not null
      or reviewer_identity is not null or authorization_reference is not null
      or cohort_reference is not null or rollback_reference is not null
      or verified_at is not null or expires_at is not null or human_authorized
      or public_access_effect or account_provisioning_effect or customer_data_effect
      or live_provider_effect or publication_effect or financial_execution_effect
      or release_effect or production_effect
  ) then
    raise exception 'Phase 8U external audience launch readiness must remain empty and fail-closed';
  end if;
end;
$$;

commit;
