insert into public.external_audience_launch_readiness_matrix (surface_template_id, gate_template_id)
select surface.id, gate.id
from public.external_audience_launch_surface_templates surface
cross join public.external_audience_launch_gate_templates gate
order by surface.sequence_number, gate.sequence_number;

