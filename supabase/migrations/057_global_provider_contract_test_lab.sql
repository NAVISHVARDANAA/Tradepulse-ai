create view public.global_provider_contract_test_status with (security_invoker=true) as
select control.*,
  (select count(*) from public.global_provider_contract_test_suites)::integer contract_suite_count,
  (select count(*) from public.global_provider_contract_test_suites where suite_status = 'specification_only')::integer specification_only_suite_count,
  (select coalesce(sum(executed_test_count),0) from public.global_provider_contract_test_suites)::integer executed_test_count,
  (select coalesce(sum(passed_test_count),0) from public.global_provider_contract_test_suites)::integer passed_test_count,
  (select count(*) from public.global_provider_contract_assertion_templates)::integer assertion_count,
  (select count(*) from public.global_provider_synthetic_fixture_templates)::integer synthetic_fixture_count,
  (select coalesce(sum(execution_count),0) from public.global_provider_synthetic_fixture_templates)::integer fixture_execution_count
from public.global_provider_contract_test_controls control;

create view public.global_provider_contract_suite_catalog with (security_invoker=true) as
select suite.id, suite.sequence_number, suite.source_family_key,
  source.display_name source_family_name, source.source_class,
  suite.suite_status, suite.schema_contract_version, suite.executed_test_count,
  suite.passed_test_count, suite.conformance_approved, suite.candidate_write_enabled,
  suite.release_enabled, suite.production_effect
from public.global_provider_contract_test_suites suite
join public.global_provider_certification_profiles certification on certification.id = suite.certification_profile_id
join public.global_observation_source_connectors source on source.id = certification.source_connector_id;

create view public.global_provider_contract_assertion_catalog with (security_invoker=true) as
select id, sequence_number, assertion_key, display_name, assertion_requirement,
  failure_disposition, blocks_external_execution, blocks_candidate_write,
  blocks_release, automatic_pass_enabled
from public.global_provider_contract_assertion_templates;

create view public.global_provider_synthetic_fixture_catalog with (security_invoker=true) as
select fixture.id, fixture.sequence_number, fixture.source_family_key,
  suite.sequence_number suite_sequence_number, fixture.fixture_key,
  fixture.fixture_class, fixture.specification, fixture.expected_disposition,
  fixture.provider_neutral, fixture.contains_external_data,
  fixture.contains_real_world_observation, fixture.execution_count,
  fixture.candidate_write_enabled, fixture.release_enabled, fixture.production_effect
from public.global_provider_synthetic_fixture_templates fixture
join public.global_provider_contract_test_suites suite on suite.id = fixture.contract_suite_id;

grant select on public.global_provider_contract_test_status,
  public.global_provider_contract_suite_catalog,
  public.global_provider_contract_assertion_catalog,
  public.global_provider_synthetic_fixture_catalog to anon, authenticated, service_role;

do $$
begin
  if (select count(*) from public.global_provider_contract_test_suites) <> 8
    or (select count(*) from public.global_provider_contract_assertion_templates) <> 10
    or (select count(*) from public.global_provider_synthetic_fixture_templates) <> 24 then
    raise exception 'Phase 8M provider contract-test reference counts changed';
  end if;
  if exists (
    select 1 from public.global_provider_contract_test_controls
    where provider_selection_enabled or endpoint_execution_enabled
      or credential_access_enabled or external_payload_intake_enabled
      or synthetic_fixture_execution_enabled or candidate_write_enabled
      or automatic_conformance_approval_enabled or observation_release_enabled
      or model_training_enabled or autonomous_publication_enabled
      or autonomous_trade_execution_enabled
  ) or exists (
    select 1 from public.global_provider_contract_test_suites
    where suite_status <> 'specification_only' or provider_legal_name is not null
      or endpoint_domain is not null or credential_reference is not null
      or external_payload_reference is not null or executed_test_count <> 0
      or passed_test_count <> 0 or conformance_approved or candidate_write_enabled
      or release_enabled or production_effect
  ) or exists (
    select 1 from public.global_provider_synthetic_fixture_templates
    where not provider_neutral or contains_external_data or contains_real_world_observation
      or execution_count <> 0 or latest_executed_at is not null
      or candidate_write_enabled or release_enabled or production_effect
  ) then
    raise exception 'Phase 8M provider contract-test laboratory must remain specification-only and fail-closed';
  end if;
  if exists (
    select 1 from public.global_provider_certification_controls
    where provider_selection_enabled or endpoint_testing_enabled
      or credential_storage_enabled or candidate_intake_enabled
      or production_ingestion_enabled or automatic_certification_enabled
      or observation_release_enabled or model_training_enabled
      or autonomous_publication_enabled or autonomous_trade_execution_enabled
  ) then
    raise exception 'The Phase 8L provider certification boundary changed';
  end if;
end;
$$;

