create table public.global_provider_synthetic_fixture_templates (
  id bigint generated by default as identity primary key,
  sequence_number smallint not null unique check (sequence_number between 1 and 24),
  contract_suite_id bigint not null references public.global_provider_contract_test_suites(id),
  source_family_key text not null,
  fixture_key text not null,
  fixture_class text not null check (fixture_class in ('valid_minimal','missing_required','schema_drift')),
  specification text not null check (char_length(specification) between 35 and 300),
  expected_disposition text not null check (expected_disposition in ('accept_to_ephemeral_test','reject_before_test')),
  provider_neutral boolean not null default true check (provider_neutral),
  contains_external_data boolean not null default false check (not contains_external_data),
  contains_real_world_observation boolean not null default false check (not contains_real_world_observation),
  execution_count integer not null default 0 check (execution_count = 0),
  latest_executed_at timestamptz check (latest_executed_at is null),
  candidate_write_enabled boolean not null default false check (not candidate_write_enabled),
  release_enabled boolean not null default false check (not release_enabled),
  production_effect boolean not null default false check (not production_effect),
  created_at timestamptz not null default now(),
  unique (source_family_key, fixture_key)
);

insert into public.global_provider_synthetic_fixture_templates (
  sequence_number, contract_suite_id, source_family_key, fixture_key,
  fixture_class, specification, expected_disposition
)
select
  ((suite.sequence_number - 1) * 3 + fixture.ordinality)::smallint,
  suite.id,
  suite.source_family_key,
  suite.source_family_key || '-' || fixture.fixture_class,
  fixture.fixture_class,
  case fixture.fixture_class
    when 'valid_minimal' then 'Specify the smallest provider-neutral shape satisfying canonical identity, version, field, unit, time and lineage requirements.'
    when 'missing_required' then 'Specify a provider-neutral shape with one required field absent so missingness is rejected without defaulting or fabrication.'
    else 'Specify a provider-neutral shape with an incompatible version or field type so schema drift is rejected deterministically.'
  end,
  case fixture.fixture_class
    when 'valid_minimal' then 'accept_to_ephemeral_test'
    else 'reject_before_test'
  end
from public.global_provider_contract_test_suites suite
cross join lateral (
  values ('valid_minimal', 1), ('missing_required', 2), ('schema_drift', 3)
) as fixture(fixture_class, ordinality)
order by suite.sequence_number, fixture.ordinality;

