select control.*,
  (select count(*) from public.global_provider_candidate_review_profiles)::integer source_family_count,
  (select count(*) from public.global_provider_activation_gate_templates)::integer activation_gate_count,
  (select count(*) from public.global_provider_activation_state_templates)::integer activation_state_count,
  (select count(*) from public.global_provider_activation_readiness_matrix)::integer readiness_cell_count,
  (select count(*) from public.global_provider_activation_readiness_matrix where readiness_status = 'blocked')::integer blocked_readiness_cell_count,
  (select count(*) from public.global_provider_activation_readiness_matrix where human_authorized)::integer authorized_readiness_cell_count
from public.global_provider_activation_controls control;

