create table public.global_market_intelligence_controls (
  control_key text primary key check (control_key = 'global-venue-instrument-intelligence'),
  reference_workspace_enabled boolean not null default true check (reference_workspace_enabled),
  policy_version text not null,
  live_market_data_connectivity_enabled boolean not null default false check (not live_market_data_connectivity_enabled),
  customer_entitlement_assignment_enabled boolean not null default false check (not customer_entitlement_assignment_enabled),
  automatic_jurisdiction_approval_enabled boolean not null default false check (not automatic_jurisdiction_approval_enabled),
  order_preview_enabled boolean not null default false check (not order_preview_enabled),
  order_routing_enabled boolean not null default false check (not order_routing_enabled),
  broker_connectivity_enabled boolean not null default false check (not broker_connectivity_enabled),
  customer_funding_enabled boolean not null default false check (not customer_funding_enabled),
  custody_enabled boolean not null default false check (not custody_enabled),
  settlement_enabled boolean not null default false check (not settlement_enabled),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.global_market_venues (
  id bigint generated by default as identity primary key,
  mic_code text not null unique check (mic_code ~ '^[A-Z0-9]{4}$'),
  venue_name text not null check (char_length(venue_name) between 3 and 120),
  country_code text not null references public.countries(iso_code),
  timezone text not null check (char_length(timezone) between 3 and 80),
  primary_currency text not null check (primary_currency ~ '^[A-Z]{3}$'),
  venue_type text not null check (venue_type in ('exchange', 'regulated_market')),
  availability_status text not null default 'reference_only' check (
    availability_status in ('reference_only', 'unavailable')
  ),
  source_name text not null,
  source_as_of date not null,
  metadata_version text not null,
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.global_market_calendars (
  id bigint generated by default as identity primary key,
  venue_id bigint not null unique references public.global_market_venues(id) on delete cascade,
  calendar_status text not null default 'review_required' check (
    calendar_status in ('verified_reference', 'review_required', 'unavailable')
  ),
  regular_session_open time,
  regular_session_close time,
  session_timezone text not null,
  holiday_calendar_status text not null default 'review_required' check (
    holiday_calendar_status in ('verified_reference', 'review_required', 'unavailable')
  ),
  settlement_convention text not null default 'source_review_required' check (
    settlement_convention in ('T+1', 'T+2', 'same_day', 'source_review_required')
  ),
  session_use_enabled boolean not null default false check (not session_use_enabled),
  source_name text not null,
  source_as_of date not null,
  calendar_version text not null,
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (
    calendar_status <> 'verified_reference'
    or (regular_session_open is not null and regular_session_close is not null)
  )
);

create table public.global_instrument_listings (
  id bigint generated by default as identity primary key,
  listing_key text not null unique,
  canonical_instrument_key text not null,
  venue_id bigint not null references public.global_market_venues(id),
  display_symbol text not null check (char_length(display_symbol) between 1 and 32),
  instrument_name text not null check (char_length(instrument_name) between 3 and 160),
  instrument_type text not null check (instrument_type in ('equity', 'etf', 'depositary_receipt')),
  quote_currency text not null check (quote_currency ~ '^[A-Z]{3}$'),
  primary_listing boolean not null default true,
  listing_status text not null default 'reference_only' check (
    listing_status in ('reference_only', 'suspended', 'delisted', 'unavailable')
  ),
  identifier_status text not null default 'review_required' check (
    identifier_status in ('verified_reference', 'review_required', 'unavailable')
  ),
  provider_mapping_status text not null default 'review_required' check (
    provider_mapping_status in ('verified_reference', 'review_required', 'unavailable')
  ),
  corporate_action_status text not null default 'review_required' check (
    corporate_action_status in ('current_reference', 'review_required', 'stale', 'unavailable')
  ),
  tick_size numeric(20,8) check (tick_size is null or tick_size > 0),
  lot_size numeric(20,8) check (lot_size is null or lot_size > 0),
  fractional_reference_status text not null default 'review_required' check (
    fractional_reference_status in ('supported_reference', 'not_supported_reference', 'review_required')
  ),
  source_name text not null,
  source_as_of date not null,
  listing_version text not null,
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (venue_id, display_symbol),
  check (listing_key = upper(listing_key)),
  check (canonical_instrument_key = upper(canonical_instrument_key))
);

create table public.global_market_data_entitlements (
  id bigint generated by default as identity primary key,
  venue_id bigint not null references public.global_market_venues(id) on delete cascade,
  dataset text not null check (dataset in ('reference', 'prices', 'corporate_actions')),
  audience_region text not null default 'GLOBAL' check (
    audience_region = 'GLOBAL' or audience_region ~ '^[A-Z]{2}$'
  ),
  display_status text not null check (
    display_status in ('reference_only', 'delayed', 'realtime', 'unavailable')
  ),
  delay_minutes integer check (delay_minutes is null or delay_minutes >= 0),
  license_status text not null check (
    license_status in ('licensed', 'public_domain', 'review_required', 'restricted')
  ),
  redistribution_allowed boolean not null default false check (not redistribution_allowed),
  browser_feed_credentials_enabled boolean not null default false check (not browser_feed_credentials_enabled),
  source_name text not null,
  source_as_of date not null,
  entitlement_version text not null,
  created_at timestamptz not null default now(),
  unique (venue_id, dataset, audience_region),
  check (display_status <> 'delayed' or delay_minutes is not null),
  check (display_status <> 'realtime' or license_status = 'licensed')
);

create table public.global_market_access_policies (
  id bigint generated by default as identity primary key,
  venue_id bigint not null references public.global_market_venues(id) on delete cascade,
  residency_country text not null references public.jurisdictions(country_code),
  customer_type text not null default 'individual' check (customer_type in ('individual', 'business')),
  investor_type text not null default 'retail' check (
    investor_type in ('retail', 'professional', 'accredited', 'institutional')
  ),
  access_status text not null check (
    access_status in ('research_only', 'review_required', 'unavailable')
  ),
  reason_code text not null,
  disclosure_status text not null default 'not_assessed' check (
    disclosure_status in ('not_assessed', 'review_required', 'complete_reference')
  ),
  legal_review_status text not null default 'review_required' check (
    legal_review_status in ('review_required', 'reference_complete')
  ),
  policy_version text not null,
  effective_from date not null,
  effective_until date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (venue_id, residency_country, customer_type, investor_type),
  check (effective_until is null or effective_until > effective_from),
  check (access_status <> 'research_only' or disclosure_status <> 'complete_reference')
);

