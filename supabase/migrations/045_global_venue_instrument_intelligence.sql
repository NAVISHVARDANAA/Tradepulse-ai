create view public.global_venue_instrument_reference
with (security_invoker = true)
as
select
  venue.id as venue_id,
  venue.mic_code,
  venue.venue_name,
  venue.country_code as venue_country_code,
  venue.timezone,
  venue.primary_currency,
  venue.availability_status as venue_availability,
  calendar.calendar_status,
  calendar.holiday_calendar_status,
  calendar.settlement_convention,
  listing.id as listing_id,
  listing.listing_key,
  listing.canonical_instrument_key,
  listing.display_symbol,
  listing.instrument_name,
  listing.instrument_type,
  listing.quote_currency,
  listing.primary_listing,
  listing.listing_status,
  listing.identifier_status,
  listing.provider_mapping_status,
  listing.corporate_action_status,
  listing.fractional_reference_status,
  access.residency_country,
  access.customer_type,
  access.investor_type,
  access.access_status,
  access.reason_code,
  access.disclosure_status,
  access.legal_review_status,
  coalesce(reference_right.display_status, 'unavailable') as reference_display_status,
  coalesce(price_right.display_status, 'unavailable') as price_display_status,
  coalesce(action_right.display_status, 'unavailable') as corporate_action_display_status,
  coalesce(reference_right.license_status, 'review_required') as reference_license_status,
  greatest(
    venue.source_as_of,
    calendar.source_as_of,
    listing.source_as_of,
    reference_right.source_as_of,
    price_right.source_as_of,
    action_right.source_as_of
  ) as reference_as_of,
  control.policy_version,
  false as live_market_data_connectivity_enabled,
  false as customer_entitlement_assignment_enabled,
  false as automatic_jurisdiction_approval_enabled,
  false as order_preview_enabled,
  false as order_routing_enabled,
  false as broker_connectivity_enabled,
  false as customer_funding_enabled,
  false as custody_enabled,
  false as settlement_enabled
from public.global_instrument_listings listing
join public.global_market_venues venue on venue.id = listing.venue_id
join public.global_market_calendars calendar on calendar.venue_id = venue.id
join public.global_market_access_policies access on access.venue_id = venue.id
cross join public.global_market_intelligence_controls control
left join public.global_market_data_entitlements reference_right
  on reference_right.venue_id = venue.id
  and reference_right.dataset = 'reference'
  and reference_right.audience_region = 'GLOBAL'
left join public.global_market_data_entitlements price_right
  on price_right.venue_id = venue.id
  and price_right.dataset = 'prices'
  and price_right.audience_region = 'GLOBAL'
left join public.global_market_data_entitlements action_right
  on action_right.venue_id = venue.id
  and action_right.dataset = 'corporate_actions'
  and action_right.audience_region = 'GLOBAL'
where venue.enabled
  and listing.enabled
  and calendar.enabled
  and control.reference_workspace_enabled;

