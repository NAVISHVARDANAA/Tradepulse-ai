  where item.asset_id = security.market_asset_id
  order by item.generated_at desc
  limit 1
) forecast on true
left join lateral (
  select item.*
  from public.equity_research_scores item
  where item.security_id = security.id
    and item.is_latest
    and item.status = 'published'
  order by item.generated_at desc
  limit 1
) research on true
left join lateral (
  select item.*
  from public.equity_fundamental_snapshots item
  where item.security_id = security.id
    and item.display_allowed
  order by item.period_end desc
  limit 1
) fundamental on true;

