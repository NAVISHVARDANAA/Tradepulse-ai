create or replace function public.evaluate_forecast_governance(
  p_as_of timestamptz default now()
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  selected_policy public.forecast_governance_policies%rowtype;
  evaluated_count integer := 0;
  snapshot_count integer := 0;
  qualified_count integer := 0;
  watch_count integer := 0;
  suspended_count integer := 0;
begin
  if auth.role() <> 'service_role' then
    raise exception 'Forecast governance evaluation requires the forecasting service';
  end if;

  if p_as_of is null or p_as_of > now() + interval '5 minutes' then
    raise exception 'Forecast governance evaluation time is invalid';
  end if;

  select * into selected_policy
  from public.forecast_governance_policies
  where active
  order by created_at desc
  limit 1;

  if not found then
    raise exception 'No active forecast governance policy is configured';
  end if;

  with due_forecasts as (
    select
      forecast.*,
      observation.price as actual_price,
      observation.observed_at as actual_observed_at
    from public.market_forecasts forecast
    join public.forecast_runs run
      on run.id = forecast.forecast_run_id
      and run.status = 'completed'
    join lateral (
      select item.price, item.observed_at
      from public.market_observations item
      where item.asset_id = forecast.asset_id
        and item.price is not null
        and item.observed_at >= forecast.target_at
        and item.observed_at <= forecast.target_at
          + make_interval(hours => selected_policy.observation_grace_hours)
        and item.observed_at <= p_as_of
      order by item.observed_at, item.id
      limit 1
    ) observation on true
    where forecast.target_at <= p_as_of
      and forecast.reference_price is not null
      and not exists (
        select 1
        from public.forecast_evaluations existing
        where existing.forecast_id = forecast.id
      )
  ), inserted_evaluations as (
    insert into public.forecast_evaluations (
      forecast_id,
      actual_price,
      absolute_error,
      absolute_percentage_error,
      directional_correct,
      evaluated_at,
      actual_observed_at,
      reference_price,
      baseline_absolute_error,
      interval_covered
    )
    select
      forecast.id,
      forecast.actual_price,
      abs(forecast.actual_price - forecast.predicted_price),
      case
        when forecast.actual_price = 0 then null
        else abs(forecast.actual_price - forecast.predicted_price)
          / forecast.actual_price * 100
      end,
      case forecast.direction
        when 'up' then forecast.actual_price > forecast.reference_price
        when 'down' then forecast.actual_price < forecast.reference_price
        else abs(
          (forecast.actual_price / forecast.reference_price - 1) * 100
        ) <= 0.15
      end,
      p_as_of,
      forecast.actual_observed_at,
      forecast.reference_price,
      abs(forecast.actual_price - forecast.reference_price),
      case
        when forecast.lower_bound is null or forecast.upper_bound is null then null
        else forecast.actual_price between forecast.lower_bound and forecast.upper_bound
      end
    from due_forecasts forecast
    on conflict (forecast_id) do nothing
    returning id
  )
  select count(*) into evaluated_count from inserted_evaluations;

  with aggregate_metrics as (
    select
      selected_policy.id as policy_id,
      selected_policy.policy_version,
      forecast.asset_id,
      forecast.model_name,
      forecast.model_version,
      forecast.horizon_hours,
      count(*)::integer as evaluation_count,
      max(evaluation.id) as source_evaluation_max_id,
      min(forecast.target_at) as evaluation_window_start,
      max(forecast.target_at) as evaluation_window_end,
      avg(evaluation.absolute_error)::numeric(20,8) as model_mae,
      avg(evaluation.baseline_absolute_error)::numeric(20,8) as baseline_mae,
      avg(evaluation.absolute_percentage_error)::numeric(12,8)
        as mean_absolute_percentage_error,
      avg(evaluation.directional_correct::integer)::numeric(5,4)
        as directional_accuracy,
      avg(evaluation.interval_covered::integer) filter (
        where evaluation.interval_covered is not null
      )::numeric(5,4) as interval_coverage
    from public.forecast_evaluations evaluation
    join public.market_forecasts forecast on forecast.id = evaluation.forecast_id
    where forecast.target_at >= p_as_of
        - make_interval(days => selected_policy.lookback_days)
      and forecast.target_at <= p_as_of
      and evaluation.baseline_absolute_error is not null
    group by
      forecast.asset_id,
      forecast.model_name,
      forecast.model_version,
      forecast.horizon_hours
  ), classified as (
    select
      metrics.*,
      case
        when metrics.baseline_mae = 0 then null
        else (
          (metrics.baseline_mae - metrics.model_mae) / metrics.baseline_mae
        ) * 100
      end as mae_improvement_pct,
      case
        when metrics.evaluation_count < selected_policy.minimum_evaluations
          then 'insufficient_evidence'
        when (
          metrics.baseline_mae > 0
          and metrics.model_mae > metrics.baseline_mae * (
            1 + selected_policy.suspension_mae_degradation_pct / 100
          )
        )
          or coalesce(metrics.directional_accuracy, 0)
            < selected_policy.suspension_directional_accuracy
          or (
            metrics.interval_coverage is not null
            and metrics.interval_coverage
              < selected_policy.suspension_interval_coverage
          ) then 'suspended'
        when (
          metrics.baseline_mae > 0
          and (
            (metrics.baseline_mae - metrics.model_mae) / metrics.baseline_mae
          ) * 100 >= selected_policy.qualified_mae_improvement_pct
          and coalesce(metrics.directional_accuracy, 0)
            >= selected_policy.qualified_directional_accuracy
          and metrics.interval_coverage between
            selected_policy.interval_coverage_min
            and selected_policy.interval_coverage_max
        ) then 'qualified'
        else 'watch'
      end as reliability_status
    from aggregate_metrics metrics
  ), prepared as (
    select
      classified.*,
      to_jsonb(array_remove(array[
        case
          when classified.evaluation_count < selected_policy.minimum_evaluations
            then 'insufficient_evidence'
        end,
        case
          when classified.baseline_mae = 0
            then 'baseline_error_zero'
          when classified.mae_improvement_pct
            < selected_policy.qualified_mae_improvement_pct
            then 'baseline_underperformance'
        end,
        case
          when coalesce(classified.directional_accuracy, 0)
            < selected_policy.qualified_directional_accuracy
            then 'directional_accuracy_low'
        end,
        case
          when classified.interval_coverage is null
            then 'interval_coverage_unavailable'
          when classified.interval_coverage
            < selected_policy.interval_coverage_min
            then 'interval_undercoverage'
          when classified.interval_coverage
            > selected_policy.interval_coverage_max
            then 'interval_overcoverage'
        end,
        case
          when classified.reliability_status = 'qualified'
            then 'production_thresholds_passed'
        end
      ]::text[], null)) as reason_codes
    from classified
  ), inserted_snapshots as (
    insert into public.forecast_reliability_snapshots (
      policy_id,
      policy_version,
      asset_id,
      model_name,
      model_version,
      horizon_hours,
      evaluation_count,
      source_evaluation_max_id,
      evaluation_window_start,
      evaluation_window_end,
      model_mae,
      baseline_mae,
      mae_improvement_pct,
      mean_absolute_percentage_error,
      directional_accuracy,
      interval_coverage,
      reliability_status,
      display_eligible,
      reason_codes,
      evaluated_at
    )
    select
      prepared.policy_id,
      prepared.policy_version,
      prepared.asset_id,
      prepared.model_name,
      prepared.model_version,
      prepared.horizon_hours,
      prepared.evaluation_count,
      prepared.source_evaluation_max_id,
      prepared.evaluation_window_start,
      prepared.evaluation_window_end,
      prepared.model_mae,
      prepared.baseline_mae,
      prepared.mae_improvement_pct,
      prepared.mean_absolute_percentage_error,
      prepared.directional_accuracy,
      prepared.interval_coverage,
      prepared.reliability_status,
      prepared.reliability_status <> 'suspended',
      prepared.reason_codes,
      p_as_of
    from prepared
    on conflict (
      policy_id,
      asset_id,
      model_name,
      model_version,
      horizon_hours,
      source_evaluation_max_id
    ) do nothing
    returning *
  ), inserted_events as (
    insert into public.model_drift_events (
      forecast_run_id,
      model_name,
      model_version,
      metric_name,
      observed_value,
      threshold_value,
      severity,
      status,
      details,
      detected_at,
      asset_id,
      horizon_hours,
      reliability_snapshot_id,
      deduplication_key
    )
    select
      null,
      snapshot.model_name,
      snapshot.model_version,
      'production_reliability_state',
      coalesce(snapshot.mae_improvement_pct, 0),
      selected_policy.qualified_mae_improvement_pct,
      case
        when snapshot.reliability_status = 'suspended' then 'critical'
        else 'warning'
      end,
      'open',
      jsonb_build_object(
        'reliabilityStatus', snapshot.reliability_status,
        'evaluationCount', snapshot.evaluation_count,
        'directionalAccuracy', snapshot.directional_accuracy,
        'intervalCoverage', snapshot.interval_coverage,
        'reasonCodes', snapshot.reason_codes,
        'policyVersion', snapshot.policy_version
      ),
      p_as_of,
      snapshot.asset_id,
      snapshot.horizon_hours,
      snapshot.id,
      concat_ws(
        ':',
        snapshot.asset_id,
        snapshot.model_name,
        snapshot.model_version,
        snapshot.horizon_hours,
        snapshot.reliability_status,
        snapshot.source_evaluation_max_id
      )
    from inserted_snapshots snapshot
    where snapshot.reliability_status in ('watch', 'suspended')
    on conflict (deduplication_key) where deduplication_key is not null
      do nothing
    returning id
  )
  select
    count(*),
    count(*) filter (where reliability_status = 'qualified'),
    count(*) filter (where reliability_status = 'watch'),
    count(*) filter (where reliability_status = 'suspended')
  into snapshot_count, qualified_count, watch_count, suspended_count
  from inserted_snapshots;

  update public.model_drift_events event
  set
    status = 'resolved',
    resolved_at = p_as_of,
    details = event.details || jsonb_build_object(
      'resolvedBy', 'forecast_governance_v1'
    )
  where event.status in ('open', 'acknowledged')
    and event.metric_name = 'production_reliability_state'
    and exists (
      select 1
      from public.forecast_reliability_snapshots snapshot
      where snapshot.asset_id = event.asset_id
        and snapshot.model_name = event.model_name
        and snapshot.model_version = event.model_version
        and snapshot.horizon_hours = event.horizon_hours
        and snapshot.reliability_status = 'qualified'
        and snapshot.id = (
          select latest.id
          from public.forecast_reliability_snapshots latest
          where latest.asset_id = event.asset_id
            and latest.model_name = event.model_name
            and latest.model_version = event.model_version
            and latest.horizon_hours = event.horizon_hours
          order by latest.evaluated_at desc, latest.id desc
          limit 1
        )
    );

  return jsonb_build_object(
    'evaluatedForecasts', evaluated_count,
    'snapshotsPublished', snapshot_count,
    'qualifiedModels', qualified_count,
    'watchModels', watch_count,
    'suspendedModels', suspended_count,
    'policyVersion', selected_policy.policy_version,
    'liveOrderRoutingEnabled', false
  );
end;
$$;

