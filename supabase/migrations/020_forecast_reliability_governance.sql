  policy_id bigint not null references public.forecast_governance_policies(id),
  policy_version text not null,
  asset_id bigint not null references public.market_assets(id) on delete cascade,
  model_name text not null,
  model_version text not null,
  horizon_hours integer not null check (horizon_hours > 0),
  evaluation_count integer not null check (evaluation_count > 0),
  source_evaluation_max_id bigint not null references public.forecast_evaluations(id),
  evaluation_window_start timestamptz not null,
  evaluation_window_end timestamptz not null,
  model_mae numeric(20,8) not null check (model_mae >= 0),
  baseline_mae numeric(20,8) not null check (baseline_mae >= 0),
  mae_improvement_pct numeric(12,6),
  mean_absolute_percentage_error numeric(12,8) check (
    mean_absolute_percentage_error is null
    or mean_absolute_percentage_error >= 0
  ),
  directional_accuracy numeric(5,4) check (
    directional_accuracy is null
    or directional_accuracy between 0 and 1
  ),
  interval_coverage numeric(5,4) check (
    interval_coverage is null
    or interval_coverage between 0 and 1
  ),
  reliability_status text not null check (
    reliability_status in (
      'insufficient_evidence',
      'qualified',
      'watch',
      'suspended'
    )
  ),
  display_eligible boolean not null,
  reason_codes jsonb not null default '[]'::jsonb check (
    jsonb_typeof(reason_codes) = 'array'
    and jsonb_array_length(reason_codes) between 1 and 10
  ),
  evaluated_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  check (evaluation_window_start <= evaluation_window_end),
  check (display_eligible = (reliability_status <> 'suspended')),
  unique (
    policy_id,
    asset_id,
    model_name,
    model_version,
    horizon_hours,
    source_evaluation_max_id
  )
);

