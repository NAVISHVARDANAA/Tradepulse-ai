create or replace view public.display_qualified_market_forecasts
with (security_invoker = true)
as
select
  forecast.*,
  asset.symbol,
  asset.name as asset_name,
  coalesce(reliability.reliability_status, 'insufficient_evidence')
    as reliability_status,
  coalesce(reliability.evaluation_count, 0) as reliability_evaluation_count,
  reliability.model_mae as production_model_mae,
  reliability.baseline_mae as production_baseline_mae,
  reliability.mae_improvement_pct as production_mae_improvement_pct,
  reliability.mean_absolute_percentage_error as production_mape,
  reliability.directional_accuracy as production_directional_accuracy,
  reliability.interval_coverage as production_interval_coverage,
  coalesce(
    reliability.reason_codes,
    '["insufficient_evidence"]'::jsonb
  ) as reliability_reason_codes,
  coalesce(reliability.display_eligible, true) as governance_display_eligible
from public.market_forecasts forecast
join public.forecast_runs run
  on run.id = forecast.forecast_run_id
  and run.status = 'completed'
join public.market_assets asset on asset.id = forecast.asset_id
left join public.forecast_reliability_latest reliability
  on reliability.asset_id = forecast.asset_id
  and reliability.model_name = forecast.model_name
  and reliability.model_version = forecast.model_version
  and reliability.horizon_hours = forecast.horizon_hours
where forecast.is_latest
  and forecast.validation_status = 'passed'
  and coalesce(reliability.display_eligible, true);

grant select on public.display_qualified_market_forecasts to anon, authenticated;

