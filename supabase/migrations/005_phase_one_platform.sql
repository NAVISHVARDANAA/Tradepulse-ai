create policy "Users manage their watchlists"
  on public.watchlists for all to authenticated
  using (user_id = auth.uid())
  with check (user_id = auth.uid());

create policy "Users manage their watchlist items"
  on public.watchlist_items for all to authenticated
  using (
    exists (
      select 1
      from public.watchlists
      where watchlists.id = watchlist_items.watchlist_id
        and watchlists.user_id = auth.uid()
    )
  )
  with check (
    exists (
      select 1
      from public.watchlists
      where watchlists.id = watchlist_items.watchlist_id
        and watchlists.user_id = auth.uid()
    )
  );

create policy "Users manage their market alerts"
  on public.market_alerts for all to authenticated
  using (user_id = auth.uid())
  with check (user_id = auth.uid());

create or replace function public.enforce_watchlist_limit()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  current_plan text;
  current_count integer;
  allowed_count integer;
begin
  select plan into current_plan
  from public.profiles
  where id = new.user_id
  for update;

  if current_plan is null then
    raise exception 'A user profile is required before creating a watchlist';
  end if;

  allowed_count := case current_plan
    when 'business' then 50
    when 'pro' then 10
    else 1
  end;

  select count(*) into current_count
  from public.watchlists
  where user_id = new.user_id;

  if current_count >= allowed_count then
    raise exception 'Watchlist limit reached for the current plan';
  end if;

  return new;
end;
$$;

create or replace function public.enforce_watchlist_item_limit()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  owner_id uuid;
  current_plan text;
  current_count integer;
  allowed_count integer;
begin
  select user_id into owner_id
  from public.watchlists
  where id = new.watchlist_id;

  select plan into current_plan
  from public.profiles
  where id = owner_id
  for update;

  allowed_count := case current_plan
    when 'business' then 250
    when 'pro' then 50
    else 5
  end;

  select count(*) into current_count
  from public.watchlist_items item
  join public.watchlists watchlist on watchlist.id = item.watchlist_id
  where watchlist.user_id = owner_id;

  if current_count >= allowed_count then
    raise exception 'Watchlist asset limit reached for the current plan';
  end if;

  return new;
end;
$$;

create or replace function public.enforce_market_alert_limit()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  current_plan text;
  current_count integer;
  allowed_count integer;
begin
  select plan into current_plan
  from public.profiles
  where id = new.user_id
  for update;

  allowed_count := case current_plan
    when 'business' then 100
    when 'pro' then 25
    else 3
  end;

  select count(*) into current_count
  from public.market_alerts
  where user_id = new.user_id;

  if current_count >= allowed_count then
    raise exception 'Market alert limit reached for the current plan';
  end if;

  return new;
end;
$$;

