create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  plan text not null default 'free' check (plan in ('free', 'pro', 'business')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.watchlists (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  is_default boolean not null default false,
  created_at timestamptz not null default now(),
  unique (user_id, name)
);

create table if not exists public.watchlist_items (
  id bigint generated by default as identity primary key,
  watchlist_id bigint not null references public.watchlists(id) on delete cascade,
  asset_id bigint not null references public.market_assets(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (watchlist_id, asset_id)
);

create table if not exists public.market_alerts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  asset_id bigint not null references public.market_assets(id) on delete cascade,
  condition text not null check (
    condition in ('price_above', 'price_below', 'change_above', 'change_below')
  ),
  target_value numeric(20,8) not null,
  enabled boolean not null default true,
  last_triggered_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.data_sync_runs (
  id bigint generated by default as identity primary key,
  source_name text not null,
  dataset text not null,
  status text not null check (status in ('running', 'completed', 'failed', 'partial')),
  records_read integer not null default 0 check (records_read >= 0),
  records_written integer not null default 0 check (records_written >= 0),
  started_at timestamptz not null default now(),
  completed_at timestamptz,
  error_summary text,
  metadata jsonb not null default '{}'::jsonb
);

create index if not exists idx_watchlists_user
