create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, display_name)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'full_name', ''))
  on conflict (id) do nothing;

  insert into public.watchlists (user_id, name, is_default)
  values (new.id, 'My Watchlist', true)
  on conflict (user_id, name) do nothing;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

insert into public.profiles (id, display_name)
select
  users.id,
  coalesce(users.raw_user_meta_data ->> 'full_name', '')
from auth.users users
on conflict (id) do nothing;

insert into public.watchlists (user_id, name, is_default)
select profiles.id, 'My Watchlist', true
from public.profiles profiles
where not exists (
  select 1
  from public.watchlists
  where watchlists.user_id = profiles.id
)
on conflict (user_id, name) do nothing;

create or replace view public.latest_market_snapshot
with (security_invoker = true)
as
select distinct on (asset.id)
  asset.id as asset_id,
  asset.symbol,
  asset.name,
  asset.asset_type,
  asset.currency,
  observation.observed_at,
  observation.price,
  observation.change_percent,
  observation.source
from public.market_assets asset
left join public.market_observations observation
  on observation.asset_id = asset.id
order by asset.id, observation.observed_at desc nulls last;

grant select on public.latest_market_snapshot to anon, authenticated;

