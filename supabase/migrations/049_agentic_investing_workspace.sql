create or replace function public.save_agentic_workspace_preferences(
  p_assistant_style text,
  p_risk_lens text,
  p_default_horizon text,
  p_default_currency text,
  p_preferred_regions text[],
  p_report_sections text[],
  p_prompt_training_opt_in boolean
)
returns public.agentic_workspace_preferences
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_preferences public.agentic_workspace_preferences;
begin
  if v_user_id is null or auth.role() <> 'authenticated' then
    raise exception 'Authentication required';
  end if;
  if p_assistant_style not in ('concise', 'balanced', 'detailed')
    or p_risk_lens not in ('conservative', 'balanced', 'growth')
    or p_default_horizon not in ('1d', '1w', '1m', '3m')
    or p_default_currency !~ '^[A-Z]{3}$'
    or cardinality(p_preferred_regions) not between 1 and 8
    or cardinality(p_report_sections) not between 1 and 8 then
    raise exception 'Invalid agentic workspace preferences';
  end if;
  if exists (
    select 1 from unnest(p_report_sections) section
    where section not in ('market_snapshot', 'forecast', 'news', 'risk', 'fundamentals', 'trade', 'methodology')
  ) then
    raise exception 'Unsupported report section';
  end if;

  insert into public.agentic_workspace_preferences (
    user_id, assistant_style, risk_lens, default_horizon, default_currency,
    preferred_regions, report_sections, prompt_training_opt_in
  ) values (
    v_user_id, p_assistant_style, p_risk_lens, p_default_horizon,
    upper(p_default_currency), p_preferred_regions, p_report_sections,
    coalesce(p_prompt_training_opt_in, false)
  )
  on conflict (user_id) do update set
    assistant_style = excluded.assistant_style,
    risk_lens = excluded.risk_lens,
    default_horizon = excluded.default_horizon,
    default_currency = excluded.default_currency,
    preferred_regions = excluded.preferred_regions,
    report_sections = excluded.report_sections,
    prompt_training_opt_in = excluded.prompt_training_opt_in
  returning * into v_preferences;
  return v_preferences;
end;
$$;

create or replace function public.save_agentic_report_definition(
  p_client_report_id text,
  p_name text,
  p_subject text,
  p_sections text[],
  p_filters jsonb,
  p_schedule text,
  p_output_format text
)
returns public.agentic_report_definitions
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_report public.agentic_report_definitions;
begin
  if v_user_id is null or auth.role() <> 'authenticated' then
    raise exception 'Authentication required';
  end if;
  if char_length(coalesce(p_client_report_id, '')) not between 8 and 100
    or char_length(trim(coalesce(p_name, ''))) not between 3 and 80
    or p_subject not in ('portfolio', 'watchlist', 'market', 'stock', 'cross_border')
    or cardinality(p_sections) not between 1 and 8
    or jsonb_typeof(p_filters) <> 'object'
    or p_schedule not in ('on_demand', 'weekdays', 'weekly')
    or p_output_format not in ('interactive', 'csv') then
    raise exception 'Invalid agentic report definition';
  end if;
  if exists (
    select 1 from unnest(p_sections) section
    where section not in ('market_snapshot', 'forecast', 'news', 'risk', 'fundamentals', 'trade', 'methodology')
  ) then
    raise exception 'Unsupported report section';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('agentic-report-user:' || v_user_id::text, 0)
  );
  if not exists (
    select 1 from public.agentic_report_definitions
    where user_id = v_user_id and client_report_id = p_client_report_id
  ) and (
    select count(*) from public.agentic_report_definitions
    where user_id = v_user_id and active
  ) >= 8 then
    raise exception 'Agentic report limit reached';
  end if;
  insert into public.agentic_report_definitions (
    user_id, client_report_id, name, subject, sections, filters, schedule, output_format
  ) values (
    v_user_id, p_client_report_id, trim(p_name), p_subject, p_sections,
    p_filters, p_schedule, p_output_format
  )
  on conflict (user_id, client_report_id) do update set
    name = excluded.name, subject = excluded.subject, sections = excluded.sections,
    filters = excluded.filters, schedule = excluded.schedule,
    output_format = excluded.output_format, active = true
  returning * into v_report;
  return v_report;
end;
$$;

