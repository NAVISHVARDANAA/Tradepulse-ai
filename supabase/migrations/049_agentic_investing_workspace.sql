  signal.expires_at, signal.synthetic
from public.global_news_signals signal
join public.global_news_signal_sources source on source.id = signal.source_id
left join public.market_assets asset on asset.id = signal.asset_id
where signal.display_eligible and signal.expires_at > now() and source.enabled;

create view public.agentic_model_learning_ledger
with (security_invoker = true)
as
select candidate_key, model_name, candidate_version, feature_schema_version,
  price_features_enabled, licensed_news_features_enabled,
  prompt_content_training_enabled, leakage_gap_enabled,
  walk_forward_validation_enabled, cost_aware_backtest_enabled,
  candidate_status, promotion_status, automatically_promoted,
  evaluation_metrics, training_data_cutoff, created_at
from public.agentic_model_training_candidates;

grant select on public.agentic_ai_control_status,
  public.global_news_signal_catalog, public.agentic_model_learning_ledger
  to anon, authenticated;
grant select on public.agentic_ai_control_status,
  public.global_news_signal_catalog, public.agentic_model_learning_ledger
  to service_role;

do $$
begin
  if exists (
    select 1 from public.agentic_ai_controls
    where external_llm_connected or unlicensed_news_ingestion_enabled
      or direct_self_promotion_enabled or autonomous_trade_execution_enabled
      or customer_funding_enabled or prompt_training_default_opt_in
  ) then
    raise exception 'Phase 8E cannot deploy with unsafe AI, news, execution, or funding capabilities';
  end if;
  if exists (
    select 1 from public.agentic_model_training_candidates
    where automatically_promoted or promotion_status <> 'human_review_required'
      or prompt_content_training_enabled
  ) then
    raise exception 'Phase 8E model candidates must remain evaluation and human-review gated';
  end if;
end;
$$;

comment on table public.agentic_ai_controls is 'Fail-closed Phase 8E AI policy: grounded research only, no autonomous execution or model promotion.';
comment on table public.global_news_signals is 'Normalized licensed or explicitly synthetic news-derived signals; raw article content is never stored.';
comment on table public.agentic_messages is 'Private account-scoped conversation history; excluded from training unless the user explicitly opts in.';
comment on table public.agentic_model_training_candidates is 'Continuous candidate-learning ledger with walk-forward evaluation and mandatory human promotion review.';
