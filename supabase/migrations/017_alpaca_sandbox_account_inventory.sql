create or replace view public.broker_account_inventory_health
with (security_invoker = true)
as
select
  provider.id as provider_id,
  provider.code as provider_code,
  provider.display_name,
  'sandbox'::text as environment,
  'https://broker-api.sandbox.alpaca.markets'::text as api_origin,
  coalesce(latest.status, 'not_run') as latest_status,
  latest.http_status,
  latest.latency_ms,
  latest.attempt_count,
  latest.total_accounts,
  latest.active_accounts,
  latest.pending_accounts,
  latest.action_required_accounts,
  latest.rejected_accounts,
  latest.closed_accounts,
  latest.restricted_accounts,
  latest.currencies,
  latest.changed_since_previous,
  latest.page_limit_reached,
  latest.error_code,
  latest.created_at as checked_at,
  true as accounts_read_enabled,
  false as orders_read_enabled,
  false as orders_write_enabled,
  provider.live_order_routing_enabled
from public.broker_provider_registry provider
left join lateral (
  select inventory.*
  from public.broker_account_inventory_runs inventory
  where inventory.provider_id = provider.id
  order by inventory.created_at desc, inventory.id desc
  limit 1
) latest on true
where provider.code = 'alpaca-broker-sandbox';

grant select on public.broker_account_inventory_health to authenticated;

