create view public.global_provider_review_decision_status with (security_invoker=true) as
select control.*,
  (select count(*) from public.global_provider_candidate_review_profiles)::integer source_family_count,
  (select count(*) from public.global_provider_review_decision_gate_templates)::integer decision_gate_count,
  (select count(*) from public.global_provider_review_decision_state_templates)::integer decision_state_count,
  (select count(*) from public.global_provider_review_decision_readiness_matrix)::integer readiness_cell_count,
  (select count(*) from public.global_provider_review_decision_readiness_matrix where readiness_status = 'unmet')::integer unmet_readiness_cell_count,
  (select count(*) from public.global_provider_review_decision_readiness_matrix where human_authorized)::integer authorized_readiness_cell_count
from public.global_provider_review_decision_controls control;

create view public.global_provider_review_decision_state_catalog with (security_invoker=true) as
