create view public.global_provider_review_decision_readiness_catalog with (security_invoker=true) as
select matrix.id, profile.source_family_key, source.display_name source_family_name,
  gate.gate_key, gate.sequence_number gate_sequence_number, gate.display_name gate_name,
  gate.review_domain, matrix.readiness_status, matrix.human_authorized,
  matrix.packet_open_effect, matrix.endpoint_access_effect,
  matrix.candidate_write_effect, matrix.release_effect, matrix.production_effect
from public.global_provider_review_decision_readiness_matrix matrix
join public.global_provider_candidate_review_profiles profile on profile.id = matrix.review_profile_id
join public.global_provider_contract_test_suites suite on suite.id = profile.contract_suite_id
join public.global_provider_certification_profiles certification on certification.id = suite.certification_profile_id
join public.global_observation_source_connectors source on source.id = certification.source_connector_id
join public.global_provider_review_decision_gate_templates gate on gate.id = matrix.decision_gate_template_id;

