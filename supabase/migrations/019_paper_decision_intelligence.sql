create or replace function public.evaluate_paper_decision_outcomes(
  p_user_id uuid,
  p_portfolio_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  decision_record record;
  outcome_observation public.market_observations%rowtype;
  asset_return numeric(16,8);
  decision_return numeric(16,8);
  forecast_error numeric(16,8);
  direction_correct boolean;
  evaluated_count integer := 0;
  insufficient_count integer := 0;
  pending_count integer := 0;
begin
  if auth.role() <> 'service_role' then
    raise exception 'This operation requires the paper-trading service';
  end if;

  if not exists (
    select 1
    from public.investment_portfolios
    where id = p_portfolio_id
      and user_id = p_user_id
      and portfolio_type = 'paper'
  ) then
    raise exception 'Paper portfolio was not found';
  end if;

  for decision_record in
    select
      context.*,
      orders.side,
      orders.status as order_status,
      instrument.market_asset_id,
      orders.submitted_at + make_interval(hours => context.planned_horizon_hours) as due_at
    from public.paper_decision_contexts context
    join public.paper_orders orders on orders.id = context.order_id
    join public.investment_instruments instrument on instrument.id = context.instrument_id
    left join public.paper_decision_outcomes outcome
      on outcome.decision_context_id = context.id
    where context.user_id = p_user_id
      and context.portfolio_id = p_portfolio_id
      and orders.status = 'filled'
      and outcome.id is null
    order by context.created_at
  loop
    if decision_record.due_at > now() then
      pending_count := pending_count + 1;
      continue;
    end if;

    select * into outcome_observation
    from public.market_observations
    where asset_id = decision_record.market_asset_id
      and observed_at >= decision_record.due_at
      and observed_at <= decision_record.due_at + interval '7 days'
      and price is not null
    order by observed_at
    limit 1;

    if not found then
      if now() <= decision_record.due_at + interval '7 days' then
        pending_count := pending_count + 1;
        continue;
      end if;

      insert into public.paper_decision_outcomes (
        decision_context_id,
        portfolio_id,
        user_id,
        evaluation_status,
        due_at
      ) values (
        decision_record.id,
        p_portfolio_id,
        p_user_id,
        'insufficient_data',
        decision_record.due_at
      );
      insufficient_count := insufficient_count + 1;
      continue;
    end if;

    asset_return := round(
      ((outcome_observation.price - decision_record.entry_price)
        / decision_record.entry_price * 100)::numeric,
      8
    );
    decision_return := case decision_record.side
      when 'buy' then asset_return
      else -asset_return
    end;
    forecast_error := case
      when decision_record.forecast_predicted_price is null
        or outcome_observation.price = 0 then null
      else round(
        (abs(decision_record.forecast_predicted_price - outcome_observation.price)
          / outcome_observation.price * 100)::numeric,
        8
      )
    end;
    direction_correct := case decision_record.forecast_direction
      when 'up' then asset_return > 0.1
      when 'down' then asset_return < -0.1
      when 'flat' then abs(asset_return) <= 0.1
      else null
    end;

    insert into public.paper_decision_outcomes (
      decision_context_id,
      portfolio_id,
      user_id,
      evaluation_status,
      due_at,
      outcome_price,
      outcome_observed_at,
      asset_return_percent,
      decision_return_percent,
      forecast_error_percent,
      forecast_direction_correct
    ) values (
      decision_record.id,
      p_portfolio_id,
      p_user_id,
      'evaluated',
      decision_record.due_at,
      outcome_observation.price,
      outcome_observation.observed_at,
      asset_return,
      decision_return,
      forecast_error,
      direction_correct
    );

    insert into public.financial_audit_events (
      user_id,
      event_type,
      resource_type,
      resource_id,
      actor_type,
      correlation_id,
      details
    ) values (
      p_user_id,
      'paper_decision_outcome_evaluated',
      'paper_decision_context',
      decision_record.id::text,
      'system',
      decision_record.order_id::text,
      jsonb_build_object(
        'evaluationVersion', 'paper-decision-v1',
        'forecastDirectionCorrect', direction_correct,
        'simulation', true,
        'liveOrderRouting', false
      )
    );

    evaluated_count := evaluated_count + 1;
  end loop;

  return jsonb_build_object(
    'evaluated', evaluated_count,
    'insufficientData', insufficient_count,
    'pending', pending_count,
    'simulation', true,
    'ordersWrite', false,
    'liveOrderRouting', false
  );
end;
$$;

revoke all on function public.evaluate_paper_decision_outcomes(uuid, uuid)
  from public, anon, authenticated;
grant execute on function public.evaluate_paper_decision_outcomes(uuid, uuid)
  to service_role;

create or replace view public.paper_decision_journal
with (security_invoker = true)
as
select
  context.id,
  context.order_id,
  context.portfolio_id,
  context.instrument_id,
  instrument.display_symbol as symbol,
  instrument.name as instrument_name,
  orders.side,
  orders.quantity,
  orders.status as order_status,
  orders.submitted_at,
  context.thesis,
  context.conviction,
  context.planned_horizon_hours,
  context.entry_price,
  context.reference_observed_at,
  context.forecast_direction,
  context.forecast_predicted_price,
  context.forecast_confidence,
  context.forecast_model_name,
  context.forecast_model_version,
  context.research_score,
  context.research_classification,
  context.research_confidence,
  context.research_methodology_version,
  context.research_risk_flags,
  orders.submitted_at + make_interval(hours => context.planned_horizon_hours) as due_at,
  coalesce(outcome.evaluation_status, 'pending') as evaluation_status,
  outcome.evaluated_at,
  outcome.outcome_price,
  outcome.outcome_observed_at,
  outcome.asset_return_percent,
  outcome.decision_return_percent,
  outcome.forecast_error_percent,
  outcome.forecast_direction_correct,
  true as simulation,
  false as orders_write_enabled,
  false as live_order_routing_enabled
from public.paper_decision_contexts context
join public.paper_orders orders on orders.id = context.order_id
join public.investment_instruments instrument on instrument.id = context.instrument_id
left join public.paper_decision_outcomes outcome
  on outcome.decision_context_id = context.id;

create or replace view public.paper_decision_scorecard
with (security_invoker = true)
as
select
  context.portfolio_id,
  count(*)::integer as total_decisions,
  count(outcome.id)::integer as completed_decisions,
  count(*) filter (where outcome.evaluation_status = 'insufficient_data')::integer
    as insufficient_data_decisions,
  count(*) filter (where outcome.forecast_direction_correct)::integer
    as correct_forecast_directions,
  round(
    100 * count(*) filter (where outcome.forecast_direction_correct)::numeric
      / nullif(count(*) filter (where outcome.forecast_direction_correct is not null), 0),
    2
  ) as forecast_directional_accuracy_percent,
  round(
    100 * count(*) filter (where outcome.decision_return_percent > 0)::numeric
      / nullif(count(*) filter (where outcome.evaluation_status = 'evaluated'), 0),
    2
  ) as profitable_decision_rate_percent,
  round(avg(outcome.decision_return_percent), 4) as average_decision_return_percent,
  round(avg(outcome.forecast_error_percent), 4) as average_forecast_error_percent,
  max(outcome.evaluated_at) as last_evaluated_at,
  true as simulation,
  false as orders_write_enabled,
  false as live_order_routing_enabled
from public.paper_decision_contexts context
left join public.paper_decision_outcomes outcome
  on outcome.decision_context_id = context.id
group by context.portfolio_id;

grant select on public.paper_decision_journal to authenticated;
grant select on public.paper_decision_scorecard to authenticated;

