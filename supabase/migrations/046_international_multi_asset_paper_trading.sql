  listing.id as listing_id, listing.listing_key, listing.canonical_instrument_key,
  listing.display_symbol, listing.instrument_name, listing.instrument_type,
  listing.quote_currency, venue.mic_code, venue.venue_name,
  venue.country_code as venue_country_code, venue.timezone,
  rules.session_state, rules.tick_size, rules.lot_size,
  rules.fractional_simulation_enabled, rules.partial_fill_simulation_enabled,
  rules.settlement_days, rules.day_order_expiry_hours, rules.rule_version,
  quote.scenario_price, quote.available_quantity, quote.quote_status,
  quote.observed_at as quote_observed_at, quote.scenario_version as quote_version,
  costs.commission_bps, costs.minimum_commission, costs.exchange_fee_bps,
  costs.tax_assumption_bps, costs.cost_status, costs.rule_version as cost_rule_version,
  false as live_market_data_enabled, false as live_order_routing_enabled,
  false as broker_connectivity_enabled, false as real_customer_funds_enabled,
