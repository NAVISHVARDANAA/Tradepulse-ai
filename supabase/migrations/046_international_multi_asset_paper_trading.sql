grant execute on function public.reconcile_international_paper_portfolio(uuid, uuid) to service_role;

do $$
begin
  if exists (select 1 from public.international_paper_trading_controls where live_market_data_enabled or live_order_routing_enabled or broker_connectivity_enabled or real_customer_funds_enabled or custody_enabled or real_settlement_enabled or margin_enabled or short_selling_enabled) then
