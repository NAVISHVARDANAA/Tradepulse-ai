-- TradePulse AI
-- Migration 046: Phase 8B international multi-asset paper trading
-- All quotes, FX rates, cash, orders, fills, positions, lots and journals in
-- this migration are deterministic simulations with no cash value and no
-- broker, market-data, custody, funding or settlement connection.

create table public.international_paper_trading_controls (
  control_key text primary key check (control_key = 'international-paper-trading'),
  simulation_enabled boolean not null default true check (simulation_enabled),
  user_initiated_simulation_enabled boolean not null default true check (user_initiated_simulation_enabled),
  policy_version text not null,
  live_market_data_enabled boolean not null default false check (not live_market_data_enabled),
  live_order_routing_enabled boolean not null default false check (not live_order_routing_enabled),
  broker_connectivity_enabled boolean not null default false check (not broker_connectivity_enabled),
  real_customer_funds_enabled boolean not null default false check (not real_customer_funds_enabled),
  custody_enabled boolean not null default false check (not custody_enabled),
  real_settlement_enabled boolean not null default false check (not real_settlement_enabled),
  margin_enabled boolean not null default false check (not margin_enabled),
  short_selling_enabled boolean not null default false check (not short_selling_enabled),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.international_paper_venue_rules (
  id bigint generated by default as identity primary key,
  venue_id bigint not null unique references public.global_market_venues(id) on delete cascade,
  session_state text not null check (session_state in ('open_scenario', 'closed_scenario', 'halted_scenario')),
  tick_size numeric(20,8) not null check (tick_size > 0),
  lot_size numeric(20,8) not null check (lot_size > 0),
  fractional_simulation_enabled boolean not null default false,
  partial_fill_simulation_enabled boolean not null default true,
  settlement_days integer not null check (settlement_days between 0 and 5),
  day_order_expiry_hours integer not null default 8 check (day_order_expiry_hours between 1 and 24),
  rules_status text not null default 'modeled_scenario' check (rules_status = 'modeled_scenario'),
  rule_version text not null,
  source_name text not null,
  source_as_of date not null,
  simulation_only boolean not null default true check (simulation_only),
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.international_paper_quotes (
  id bigint generated by default as identity primary key,
  listing_id bigint not null unique references public.global_instrument_listings(id) on delete cascade,
  scenario_price numeric(20,8) not null check (scenario_price > 0),
  available_quantity numeric(24,8) not null check (available_quantity >= 0),
  quote_status text not null check (quote_status in ('available_scenario', 'halted_scenario', 'unavailable')),
  observed_at timestamptz not null,
  scenario_version text not null,
  source_name text not null,
  source_type text not null default 'deterministic_fixture' check (source_type = 'deterministic_fixture'),
  simulation_only boolean not null default true check (simulation_only),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.international_paper_fx_rates (
  currency_code text primary key check (currency_code ~ '^[A-Z]{3}$'),
  usd_value_per_unit numeric(24,10) not null check (usd_value_per_unit > 0),
  conversion_spread_bps numeric(10,4) not null check (conversion_spread_bps between 0 and 1000),
  rate_status text not null default 'modeled_scenario' check (rate_status = 'modeled_scenario'),
  scenario_version text not null,
  source_name text not null,
  source_as_of date not null,
  simulation_only boolean not null default true check (simulation_only),
  updated_at timestamptz not null default now()
);

create table public.international_paper_cost_rules (
  id bigint generated by default as identity primary key,
  venue_id bigint not null references public.global_market_venues(id) on delete cascade,
  instrument_type text not null check (instrument_type in ('equity', 'etf', 'depositary_receipt')),
  commission_bps numeric(10,4) not null check (commission_bps >= 0),
  minimum_commission numeric(20,8) not null check (minimum_commission >= 0),
  exchange_fee_bps numeric(10,4) not null check (exchange_fee_bps >= 0),
  tax_assumption_bps numeric(10,4) not null check (tax_assumption_bps >= 0),
  cost_status text not null default 'modeled_scenario' check (cost_status in ('modeled_scenario', 'unavailable')),
  rule_version text not null,
  source_name text not null,
  source_as_of date not null,
  simulation_only boolean not null default true check (simulation_only),
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (venue_id, instrument_type)
);

create table public.international_paper_accounts (
  portfolio_id uuid primary key references public.investment_portfolios(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  base_currency text not null check (base_currency ~ '^[A-Z]{3}$'),
  account_status text not null default 'active' check (account_status in ('active', 'paused')),
  max_order_value_usd numeric(24,8) not null default 25000 check (max_order_value_usd > 0),
  simulation_only boolean not null default true check (simulation_only),
  live_account_id text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (live_account_id is null),
  unique (user_id, portfolio_id)
);

create table public.international_paper_cash_balances (
  portfolio_id uuid not null references public.international_paper_accounts(portfolio_id) on delete cascade,
  currency text not null references public.international_paper_fx_rates(currency_code),
  balance numeric(24,8) not null default 0 check (balance >= 0),
  available_balance numeric(24,8) not null default 0 check (available_balance >= 0),
  simulation_only boolean not null default true check (simulation_only),
  updated_at timestamptz not null default now(),
  primary key (portfolio_id, currency),
  check (available_balance <= balance)
);

create table public.international_paper_orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  portfolio_id uuid not null references public.international_paper_accounts(portfolio_id) on delete cascade,
  listing_id bigint not null references public.global_instrument_listings(id),
  client_order_id text not null check (char_length(client_order_id) between 8 and 100),
  side text not null check (side in ('buy', 'sell')),
  order_type text not null check (order_type in ('market', 'limit', 'stop', 'stop_limit')),
  time_in_force text not null check (time_in_force in ('day', 'gtc', 'ioc')),
  quantity numeric(24,8) not null check (quantity > 0),
  limit_price numeric(20,8) check (limit_price is null or limit_price > 0),
  stop_price numeric(20,8) check (stop_price is null or stop_price > 0),
  status text not null check (status in ('accepted', 'risk_rejected', 'partially_filled', 'filled', 'halted', 'expired')),
  filled_quantity numeric(24,8) not null default 0 check (filled_quantity between 0 and quantity),
  average_fill_price numeric(20,8) check (average_fill_price is null or average_fill_price > 0),
  quote_currency text not null check (quote_currency ~ '^[A-Z]{3}$'),
  commission numeric(20,8) not null default 0 check (commission >= 0),
  exchange_fee numeric(20,8) not null default 0 check (exchange_fee >= 0),
  tax_assumption numeric(20,8) not null default 0 check (tax_assumption >= 0),
  total_cost numeric(20,8) not null default 0 check (total_cost >= 0),
  rejection_reason text,
  quote_observed_at timestamptz,
  expires_at timestamptz,
  simulation_rule_version text not null,
  simulation_only boolean not null default true check (simulation_only),
  live_order_id text,
  submitted_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, client_order_id),
  check (live_order_id is null),
  check (order_type not in ('limit', 'stop_limit') or limit_price is not null),
  check (order_type not in ('stop', 'stop_limit') or stop_price is not null)
);

