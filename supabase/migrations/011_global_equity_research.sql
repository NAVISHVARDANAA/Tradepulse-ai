create table if not exists public.equity_securities (
  id bigint generated by default as identity primary key,
  market_asset_id bigint not null unique references public.market_assets(id) on delete cascade,
  instrument_id bigint unique references public.investment_instruments(id) on delete set null,
  security_key text not null unique,
  display_symbol text not null,
  company_name text not null,
  asset_class text not null default 'equity' check (asset_class in ('equity', 'etf')),
  exchange_code text not null,
  exchange_name text,
  exchange_mic text,
  country_code text check (country_code is null or country_code ~ '^[A-Z]{2}$'),
  quote_currency text not null check (quote_currency ~ '^[A-Z]{3}$'),
  sector text,
  industry text,
  cik text check (cik is null or cik ~ '^[0-9]{10}$'),
  isin text,
  provider_name text not null,
  provider_symbol text not null,
  research_enabled boolean not null default true,
  forecast_enabled boolean not null default true,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (provider_name, provider_symbol)
);

create table if not exists public.equity_data_coverage (
  id bigint generated by default as identity primary key,
  security_id bigint not null references public.equity_securities(id) on delete cascade,
  provider_name text not null,
  dataset text not null check (dataset in ('reference', 'prices', 'fundamentals', 'news')),
  coverage_status text not null default 'reference' check (
    coverage_status in ('reference', 'delayed', 'realtime', 'unavailable')
  ),
  delay_minutes integer check (delay_minutes is null or delay_minutes >= 0),
  license_status text not null default 'review_required' check (
    license_status in ('public_domain', 'licensed', 'review_required', 'restricted')
  ),
  last_synchronized_at timestamptz,
  last_observed_at timestamptz,
  error_summary text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (security_id, provider_name, dataset)
);

create table if not exists public.equity_fundamental_snapshots (
  id bigint generated by default as identity primary key,
  security_id bigint not null references public.equity_securities(id) on delete cascade,
  period_end date not null,
  filing_date date,
  fiscal_period text not null,
  currency text not null check (currency ~ '^[A-Z]{3}$'),
  revenue numeric(28,4),
  net_income numeric(28,4),
  diluted_eps numeric(20,8),
  total_assets numeric(28,4),
  total_liabilities numeric(28,4),
  operating_cash_flow numeric(28,4),
  capital_expenditure numeric(28,4),
  shares_outstanding numeric(28,4),
  pe_ratio numeric(16,6),
  price_to_book numeric(16,6),
  dividend_yield numeric(12,8),
  source text not null,
  source_url text,
  display_allowed boolean not null default false,
  fetched_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  unique (security_id, period_end, fiscal_period, source)
);

create table if not exists public.equity_research_scores (
  id bigint generated by default as identity primary key,
  security_id bigint not null references public.equity_securities(id) on delete cascade,
  generated_at timestamptz not null default now(),
  as_of_time timestamptz not null,
  score numeric(6,3) not null check (score between 0 and 100),
  classification text not null check (
    classification in ('research_positive', 'research_neutral', 'research_cautious', 'insufficient_data')
  ),
  confidence numeric(5,4) not null check (confidence between 0 and 1),
  forecast_score numeric(6,3) not null check (forecast_score between 0 and 100),
  momentum_score numeric(6,3) not null check (momentum_score between 0 and 100),
  quality_score numeric(6,3) not null check (quality_score between 0 and 100),
  valuation_score numeric(6,3) not null check (valuation_score between 0 and 100),
  risk_score numeric(6,3) not null check (risk_score between 0 and 100),
  data_quality_score numeric(6,3) not null check (data_quality_score between 0 and 100),
  methodology_version text not null,
  reasons jsonb not null default '[]'::jsonb,
  risk_flags jsonb not null default '[]'::jsonb,
  status text not null default 'draft' check (status in ('draft', 'published', 'withdrawn')),
  is_latest boolean not null default true,
  created_at timestamptz not null default now()
);

