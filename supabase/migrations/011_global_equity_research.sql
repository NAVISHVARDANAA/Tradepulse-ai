create or replace view public.equity_research_dashboard
with (security_invoker = true)
as
select
  security.id as security_id,
  security.market_asset_id,
  security.display_symbol,
  security.company_name,
  security.asset_class,
  security.exchange_code,
  security.exchange_name,
  security.exchange_mic,
  security.country_code,
  security.quote_currency,
  security.sector,
  security.industry,
  security.provider_name,
  security.provider_symbol,
  security.forecast_enabled,
  coverage.coverage_status,
  coverage.delay_minutes,
  coverage.license_status,
  coverage.last_synchronized_at,
  observation.observed_at,
  observation.price,
  observation.change_percent,
  observation.source as price_source,
  forecast.id as forecast_id,
  forecast.generated_at as forecast_generated_at,
  forecast.target_at as forecast_target_at,
  forecast.horizon_hours,
  forecast.predicted_price,
  forecast.lower_bound,
  forecast.upper_bound,
  forecast.confidence_score as forecast_confidence,
  forecast.direction as forecast_direction,
  forecast.model_name,
  forecast.model_version,
  forecast.baseline_mae,
  forecast.model_mae,
  forecast.directional_accuracy,
  research.generated_at as research_generated_at,
  research.score as research_score,
  research.classification as research_classification,
  research.confidence as research_confidence,
  research.forecast_score,
  research.momentum_score,
  research.quality_score,
  research.valuation_score,
  research.risk_score,
  research.data_quality_score,
  research.methodology_version,
  research.reasons,
  research.risk_flags,
  fundamental.period_end as fundamental_period_end,
  fundamental.revenue,
  fundamental.net_income,
  fundamental.diluted_eps,
  fundamental.pe_ratio,
  fundamental.price_to_book,
  fundamental.dividend_yield
from public.equity_securities security
left join lateral (
  select item.*
  from public.equity_data_coverage item
  where item.security_id = security.id
    and item.dataset = 'prices'
  order by item.last_synchronized_at desc nulls last
  limit 1
) coverage on true
left join lateral (
  select item.*
  from public.market_observations item
  where item.asset_id = security.market_asset_id
  order by item.observed_at desc
  limit 1
) observation on true
left join lateral (
  select item.*
  from public.market_forecasts item
  where item.asset_id = security.market_asset_id
    and item.is_latest
    and item.validation_status = 'passed'
  order by item.generated_at desc
  limit 1
) forecast on true
left join lateral (
  select item.*
  from public.equity_research_scores item
  where item.security_id = security.id
    and item.is_latest
    and item.status = 'published'
  order by item.generated_at desc
  limit 1
) research on true
left join lateral (
  select item.*
  from public.equity_fundamental_snapshots item
  where item.security_id = security.id
    and item.display_allowed
  order by item.period_end desc
  limit 1
) fundamental on true;

grant select on public.equity_research_dashboard to anon, authenticated;

