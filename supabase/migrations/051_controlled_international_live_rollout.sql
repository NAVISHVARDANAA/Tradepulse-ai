create view public.controlled_live_rollout_status with (security_invoker=true) as
select control.*,
  (select count(*) from public.controlled_live_rollout_cohorts)::integer candidate_cohort_count,
  (select count(*) from public.controlled_live_rollout_requirements)::integer requirement_count,
  (select count(*) from public.controlled_live_rollout_drill_templates)::integer drill_template_count,
  (select count(*) from public.controlled_live_rollout_drill_observations)::integer observed_drill_count
from public.controlled_live_rollout_controls control;

create view public.controlled_live_rollout_cohort_catalog with (security_invoker=true) as
select cohort.id cohort_id, cohort.cohort_key, cohort.cohort_label,
  cohort.residency_country, cohort.execution_jurisdiction, cohort.mic_code,
  venue.venue_name, cohort.settlement_currency, cohort.account_type,
  cohort.asset_class, cohort.allowed_order_types, cohort.maximum_customer_count,
  cohort.approval_status, cohort.activation_status,
  (select count(*) from public.controlled_live_rollout_scope_decisions d where d.cohort_id=cohort.id)::integer scope_decision_count,
  (select count(*) from public.controlled_live_rollout_scope_decisions d where d.cohort_id=cohort.id and d.decision_status='review_required')::integer open_scope_decision_count,
  (select count(*) from public.controlled_live_rollout_gate_reviews g where g.cohort_id=cohort.id)::integer gate_count,
  (select count(*) from public.controlled_live_rollout_gate_reviews g where g.cohort_id=cohort.id and g.review_status='evidence_missing')::integer blocking_gate_count
from public.controlled_live_rollout_cohorts cohort
join public.global_brokerage_launch_matrix matrix on matrix.id=cohort.launch_matrix_id
join public.global_market_venues venue on venue.id=matrix.venue_id;

create view public.controlled_live_rollout_limit_catalog with (security_invoker=true) as
select cohort.cohort_key, cohort.settlement_currency, policy.*
from public.controlled_live_rollout_limit_policies policy
join public.controlled_live_rollout_cohorts cohort on cohort.id=policy.cohort_id;

create view public.controlled_live_rollout_gate_catalog with (security_invoker=true) as
select requirement.*,
  (select count(*) from public.controlled_live_rollout_gate_reviews g where g.requirement_id=requirement.id)::integer cohort_review_count,
  (select count(*) from public.controlled_live_rollout_gate_reviews g where g.requirement_id=requirement.id and g.review_status='evidence_missing')::integer blocking_review_count
from public.controlled_live_rollout_requirements requirement;

create view public.controlled_live_rollout_drill_catalog with (security_invoker=true) as
select template.*,
  (select count(*) from public.controlled_live_rollout_drill_observations o where o.drill_template_id=template.id)::integer observed_count,
  (select max(observed_at) from public.controlled_live_rollout_drill_observations o where o.drill_template_id=template.id) latest_observed_at
from public.controlled_live_rollout_drill_templates template;

