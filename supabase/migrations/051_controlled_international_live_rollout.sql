create table public.controlled_live_rollout_cohorts (
  id bigint generated by default as identity primary key,
  cohort_key text not null unique,
  launch_matrix_id bigint not null unique references public.global_brokerage_launch_matrix(id),
  cohort_label text not null,
  residency_country text not null check (residency_country ~ '^[A-Z]{2}$'),
  execution_jurisdiction text not null check (execution_jurisdiction ~ '^[A-Z]{2}$'),
  mic_code text not null check (mic_code ~ '^[A-Z0-9]{4}$'),
  settlement_currency text not null check (settlement_currency ~ '^[A-Z]{3}$'),
  customer_type text not null default 'individual' check (customer_type = 'individual'),
  investor_type text not null default 'retail' check (investor_type = 'retail'),
  account_type text not null default 'cash' check (account_type = 'cash'),
  asset_class text not null default 'equity' check (asset_class = 'equity'),
  allowed_order_types text[] not null default array['market','limit']::text[]
    check (allowed_order_types = array['market','limit']::text[]),
  maximum_customer_count integer not null check (maximum_customer_count between 1 and 50),
  cohort_status text not null default 'candidate' check (cohort_status = 'candidate'),
  approval_status text not null default 'approval_required' check (approval_status = 'approval_required'),
  activation_status text not null default 'blocked' check (activation_status = 'blocked'),
  production_enabled boolean not null default false check (not production_enabled),
  decision_version text not null default 'controlled-live-cohort-v1',
  source_as_of date not null,
  created_at timestamptz not null default now(),
  check (residency_country = execution_jurisdiction)
);

insert into public.controlled_live_rollout_cohorts (
  cohort_key, launch_matrix_id, cohort_label, residency_country,
  execution_jurisdiction, mic_code, settlement_currency,
  maximum_customer_count, source_as_of
)
select seed.cohort_key, matrix.id, seed.label, matrix.residency_country,
  matrix.execution_jurisdiction, venue.mic_code, matrix.settlement_currency,
  seed.maximum_customer_count, date '2026-09-13'
from (values
  ('IN:XNSE:CASH:EQUITY:COHORT-01', 'IN:XNSE:CASH:EQUITY', 'India cash-equity candidate', 20),
  ('GB:XLON:CASH:EQUITY:COHORT-01', 'GB:XLON:CASH:EQUITY', 'United Kingdom cash-equity candidate', 20),
  ('US:XNAS:CASH:EQUITY:COHORT-01', 'US:XNAS:CASH:EQUITY', 'United States cash-equity candidate', 25)
) seed(cohort_key, matrix_code, label, maximum_customer_count)
join public.global_brokerage_launch_matrix matrix on matrix.matrix_code = seed.matrix_code
join public.global_market_venues venue on venue.id = matrix.venue_id
where matrix.account_type = 'cash' and matrix.asset_class = 'equity';

