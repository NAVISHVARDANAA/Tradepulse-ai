create table public.controlled_live_rollout_scope_decisions (
  id bigint generated by default as identity primary key,
  cohort_id bigint not null references public.controlled_live_rollout_cohorts(id),
  scope_dimension text not null check (scope_dimension in (
    'residency','execution_jurisdiction','venue','currency','customer_type',
    'investor_type','account_type','asset_class','market_order','limit_order'
  )),
  scope_value text not null,
  decision_status text not null default 'review_required' check (decision_status = 'review_required'),
  approval_inherited boolean not null default false check (not approval_inherited),
  production_effect boolean not null default false check (not production_effect),
  decision_version text not null default 'controlled-live-scope-decision-v1',
  unique (cohort_id, scope_dimension)
);

insert into public.controlled_live_rollout_scope_decisions (cohort_id, scope_dimension, scope_value)
select cohort.id, scope.dimension,
  case scope.dimension
    when 'residency' then cohort.residency_country
    when 'execution_jurisdiction' then cohort.execution_jurisdiction
    when 'venue' then cohort.mic_code when 'currency' then cohort.settlement_currency
    when 'customer_type' then cohort.customer_type when 'investor_type' then cohort.investor_type
    when 'account_type' then cohort.account_type when 'asset_class' then cohort.asset_class
    when 'market_order' then 'market' when 'limit_order' then 'limit'
  end
from public.controlled_live_rollout_cohorts cohort
cross join (values ('residency'),('execution_jurisdiction'),('venue'),('currency'),
  ('customer_type'),('investor_type'),('account_type'),('asset_class'),
  ('market_order'),('limit_order')) scope(dimension);

