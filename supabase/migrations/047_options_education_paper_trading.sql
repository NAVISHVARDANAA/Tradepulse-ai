  collateral_amount numeric(24,8) not null check (collateral_amount >= 0),
  max_profit numeric(24,8) check (max_profit is null or max_profit >= 0),
  max_loss numeric(24,8) not null check (max_loss >= 0),
  break_even_price numeric(20,8) not null check (break_even_price >= 0),
