create table public.options_chain_entitlements (
  id bigint generated by default as identity primary key,
  venue_id bigint not null references public.global_market_venues(id) on delete cascade,
  audience_region text not null default 'GLOBAL' check (
    audience_region = 'GLOBAL' or audience_region ~ '^[A-Z]{2}$'
  ),
  display_status text not null check (display_status in ('deterministic_education', 'unavailable')),
  educational_display_permitted boolean not null default false,
  live_display_rights_confirmed boolean not null default false check (not live_display_rights_confirmed),
  source_name text not null,
  source_as_of date not null,
  entitlement_version text not null,
  simulation_only boolean not null default true check (simulation_only),
  created_at timestamptz not null default now(),
  unique (venue_id, audience_region),
  check (display_status <> 'deterministic_education' or educational_display_permitted)
);

create table public.options_chain_scenarios (
  id bigint generated by default as identity primary key,
  underlying_listing_id bigint not null references public.global_instrument_listings(id) on delete cascade,
  entitlement_id bigint not null references public.options_chain_entitlements(id),
  contract_symbol text not null unique check (contract_symbol = upper(contract_symbol)),
  option_type text not null check (option_type in ('call', 'put')),
  expires_on date not null,
  strike numeric(20,8) not null check (strike > 0),
  contract_multiplier integer not null default 100 check (contract_multiplier = 100),
  bid numeric(20,8) not null check (bid >= 0),
  ask numeric(20,8) not null check (ask >= bid and ask > 0),
  volume integer not null check (volume >= 0),
  open_interest integer not null check (open_interest >= 0),
  implied_volatility numeric(12,8) not null check (implied_volatility between 0 and 5),
  delta numeric(12,8) not null check (delta between -1 and 1),
  gamma numeric(12,8) not null check (gamma between 0 and 1),
  theta numeric(12,8) not null check (theta between -10 and 0),
  vega numeric(12,8) not null check (vega between 0 and 10),
  quote_observed_at timestamptz not null,
  freshness_status text not null check (freshness_status in ('scenario_current', 'scenario_stale', 'unavailable')),
  scenario_version text not null,
  source_name text not null,
  source_type text not null default 'deterministic_fixture' check (source_type = 'deterministic_fixture'),
  corporate_action_adjusted boolean not null default false,
  simulation_only boolean not null default true check (simulation_only),
  live_contract_id text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (underlying_listing_id, expires_on, strike, option_type),
  check (live_contract_id is null)
);

