create view public.options_paper_chain_catalog
with (security_invoker = true)
as
select
  chain.id as contract_id,
  listing.id as underlying_listing_id,
  listing.listing_key as underlying_listing_key,
  listing.display_symbol as underlying_symbol,
  listing.instrument_name as underlying_name,
  listing.quote_currency,
  underlying_quote.scenario_price as underlying_scenario_price,
  venue.mic_code,
  chain.contract_symbol,
  chain.option_type,
  chain.expires_on,
  chain.strike,
  chain.contract_multiplier,
  chain.bid,
  chain.ask,
  chain.volume,
  chain.open_interest,
  chain.implied_volatility,
  chain.delta,
  chain.gamma,
  chain.theta,
  chain.vega,
  chain.quote_observed_at,
  chain.freshness_status,
  chain.corporate_action_adjusted,
  chain.scenario_version,
  chain.simulation_only,
  entitlement.display_status,
  entitlement.educational_display_permitted,
  entitlement.live_display_rights_confirmed,
  controls.live_market_data_enabled,
  controls.live_options_routing_enabled,
  controls.broker_connectivity_enabled,
  controls.margin_enabled,
  controls.uncovered_short_options_enabled
from public.options_chain_scenarios chain
join public.global_instrument_listings listing on listing.id = chain.underlying_listing_id
join public.global_market_venues venue on venue.id = listing.venue_id
join public.international_paper_quotes underlying_quote on underlying_quote.listing_id = listing.id
join public.options_chain_entitlements entitlement on entitlement.id = chain.entitlement_id
cross join public.options_paper_controls controls
where entitlement.display_status = 'deterministic_education'
  and entitlement.educational_display_permitted
  and chain.freshness_status <> 'unavailable';

