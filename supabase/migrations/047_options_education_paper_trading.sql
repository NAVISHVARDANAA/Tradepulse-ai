create or replace function public.initialize_options_paper_account(
  p_user_id uuid,
  p_portfolio_id uuid,
  p_starting_cash numeric,
  p_experience_level text,
  p_objective text,
  p_loss_tolerance text,
  p_jurisdiction_code text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_inserted integer := 0;
  v_journal_id uuid;
begin
  if current_setting('request.jwt.claim.role', true) <> 'service_role' then
    raise exception 'Options paper accounts require the simulation service';
  end if;
  if p_starting_cash < 1000 or p_starting_cash > 1000000 then
    raise exception 'Invalid options virtual balance';
  end if;
  if p_experience_level not in ('none', 'beginner', 'intermediate', 'advanced')
    or p_objective not in ('education', 'hedging', 'income', 'growth')
    or p_loss_tolerance not in ('low', 'medium', 'high')
    or p_jurisdiction_code !~ '^[A-Z]{2}$' then
    raise exception 'Invalid options education assessment';
  end if;
  if not exists (
    select 1 from public.investment_portfolios
    where id = p_portfolio_id and user_id = p_user_id and portfolio_type = 'paper'
  ) then
    raise exception 'Paper portfolio not found';
  end if;

  insert into public.options_paper_accounts (
    portfolio_id, user_id, starting_cash, cash_balance
  ) values (
    p_portfolio_id, p_user_id, p_starting_cash, p_starting_cash
  ) on conflict (portfolio_id) do nothing;
  get diagnostics v_inserted = row_count;

  if not exists (
    select 1 from public.options_paper_accounts
    where portfolio_id = p_portfolio_id and user_id = p_user_id
  ) then
    raise exception 'Options paper account belongs to another user';
  end if;

  insert into public.options_paper_appropriateness_profiles (
    portfolio_id, user_id, experience_level, objective, loss_tolerance,
    jurisdiction_code
  ) values (
    p_portfolio_id, p_user_id, p_experience_level, p_objective,
    p_loss_tolerance, p_jurisdiction_code
  )
  on conflict (portfolio_id) do update set
    experience_level = excluded.experience_level,
    objective = excluded.objective,
    loss_tolerance = excluded.loss_tolerance,
    jurisdiction_code = excluded.jurisdiction_code,
    assessed_at = now();

  if v_inserted = 1 then
    insert into public.options_paper_journal_entries (
      user_id, portfolio_id, entry_type, correlation_id
    ) values (
      p_user_id, p_portfolio_id, 'initial_credit', 'options-initial-' || p_portfolio_id::text
    ) returning id into v_journal_id;
    insert into public.options_paper_journal_lines (journal_entry_id, account_code, amount)
    values
      (v_journal_id, 'virtual_cash', p_starting_cash),
      (v_journal_id, 'simulation_equity', -p_starting_cash);
  end if;

  return jsonb_build_object(
    'status', case when v_inserted = 1 then 'created' else 'updated' end,
    'assessmentStatus', 'education_only',
    'liveOptionsPermission', false
  );
end;
$$;

create or replace function public.create_options_paper_strategy(
  p_user_id uuid,
  p_portfolio_id uuid,
  p_client_strategy_id text,
  p_strategy_type text,
  p_long_contract_id bigint,
  p_short_contract_id bigint,
  p_contracts integer
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_account public.options_paper_accounts%rowtype;
  v_long public.options_chain_scenarios%rowtype;
  v_short public.options_chain_scenarios%rowtype;
  v_existing uuid;
  v_strategy_id uuid;
  v_journal_id uuid;
  v_width numeric(20,8);
  v_debit numeric(20,8);
  v_max_loss numeric(24,8);
  v_max_profit numeric(24,8);
  v_break_even numeric(20,8);
  v_profit_potential text := 'bounded';
begin
  if current_setting('request.jwt.claim.role', true) <> 'service_role' then
    raise exception 'Options paper strategies require the simulation service';
  end if;
  if char_length(coalesce(p_client_strategy_id, '')) not between 8 and 100
    or p_strategy_type not in ('long_call', 'long_put', 'bull_call_spread', 'bear_put_spread')
    or p_contracts not between 1 and 100 then
    raise exception 'Invalid options paper strategy';
  end if;

  select id into v_existing from public.options_paper_strategies
  where user_id = p_user_id and client_strategy_id = p_client_strategy_id;
  if v_existing is not null then
    return jsonb_build_object('status', 'open', 'strategyId', v_existing, 'idempotentReplay', true);
  end if;

  select * into v_account from public.options_paper_accounts
  where portfolio_id = p_portfolio_id and user_id = p_user_id for update;
  if v_account.portfolio_id is null or v_account.account_status <> 'active' then
    raise exception 'Options paper account is unavailable';
  end if;
  if not exists (
    select 1 from public.options_paper_appropriateness_profiles
    where portfolio_id = p_portfolio_id and user_id = p_user_id
      and assessment_status = 'education_only' and simulation_access_enabled
      and not live_options_permission_enabled and not forecast_permission_override_enabled
  ) then
    raise exception 'Options education assessment is unavailable';
  end if;

  select * into v_long from public.options_chain_scenarios where id = p_long_contract_id;
  if v_long.id is null or v_long.freshness_status <> 'scenario_current'
    or not v_long.simulation_only or v_long.source_type <> 'deterministic_fixture' then
    raise exception 'Selected options scenario is unavailable';
  end if;

  if p_strategy_type in ('long_call', 'long_put') then
    if p_short_contract_id is not null
      or (p_strategy_type = 'long_call' and v_long.option_type <> 'call')
      or (p_strategy_type = 'long_put' and v_long.option_type <> 'put') then
      raise exception 'Single-leg strategy contract mismatch';
    end if;
    v_debit := v_long.ask;
    v_max_loss := v_debit * v_long.contract_multiplier * p_contracts;
    v_break_even := case when v_long.option_type = 'call'
      then v_long.strike + v_debit else greatest(v_long.strike - v_debit, 0) end;
    if p_strategy_type = 'long_call' then
      v_max_profit := null;
      v_profit_potential := 'unbounded';
    else
      v_max_profit := greatest(v_long.strike - v_debit, 0) * v_long.contract_multiplier * p_contracts;
    end if;
  else
    select * into v_short from public.options_chain_scenarios where id = p_short_contract_id;
    if v_short.id is null
      or v_short.underlying_listing_id <> v_long.underlying_listing_id
      or v_short.expires_on <> v_long.expires_on
      or v_short.option_type <> v_long.option_type
      or v_short.contract_multiplier <> v_long.contract_multiplier then
      raise exception 'Defined-risk spread legs do not match';
    end if;
    if (p_strategy_type = 'bull_call_spread' and (
        v_long.option_type <> 'call' or v_long.strike >= v_short.strike
      )) or (p_strategy_type = 'bear_put_spread' and (
        v_long.option_type <> 'put' or v_long.strike <= v_short.strike
      )) then
      raise exception 'Spread direction is not defined risk';
    end if;
    v_width := abs(v_short.strike - v_long.strike);
    v_debit := v_long.ask - v_short.bid;
    if v_debit <= 0 or v_debit >= v_width then
      raise exception 'Spread premium does not preserve bounded risk';
    end if;
    v_max_loss := v_debit * v_long.contract_multiplier * p_contracts;
    v_max_profit := (v_width - v_debit) * v_long.contract_multiplier * p_contracts;
    v_break_even := case when p_strategy_type = 'bull_call_spread'
      then v_long.strike + v_debit else v_long.strike - v_debit end;
  end if;

  if v_account.cash_balance < v_max_loss then
    raise exception 'Insufficient options virtual cash';
  end if;

  insert into public.options_paper_strategies (
    user_id, portfolio_id, client_strategy_id, strategy_type,
    underlying_listing_id, expires_on, contracts, contract_multiplier,
    net_debit_per_share, collateral_amount, max_profit, max_loss,
    break_even_price, profit_potential
  ) values (
    p_user_id, p_portfolio_id, p_client_strategy_id, p_strategy_type,
    v_long.underlying_listing_id, v_long.expires_on, p_contracts, v_long.contract_multiplier,
    v_debit, v_max_loss, v_max_profit, v_max_loss,
    v_break_even, v_profit_potential
  ) returning id into v_strategy_id;

  insert into public.options_paper_legs (
    strategy_id, contract_id, side, opening_price, protective_long_leg_required
  ) values (v_strategy_id, v_long.id, 'long', v_long.ask, false);
  if v_short.id is not null then
    insert into public.options_paper_legs (
      strategy_id, contract_id, side, opening_price, protective_long_leg_required
    ) values (v_strategy_id, v_short.id, 'short', v_short.bid, true);
  end if;

  update public.options_paper_accounts
  set cash_balance = cash_balance - v_max_loss
  where portfolio_id = p_portfolio_id;

  insert into public.options_paper_journal_entries (
    user_id, portfolio_id, strategy_id, entry_type, correlation_id
  ) values (
    p_user_id, p_portfolio_id, v_strategy_id, 'strategy_open', p_client_strategy_id
  ) returning id into v_journal_id;
  insert into public.options_paper_journal_lines (journal_entry_id, account_code, amount)
  values
    (v_journal_id, 'virtual_cash', -v_max_loss),
    (v_journal_id, 'option_premium_asset', v_max_loss);

  return jsonb_build_object(
    'status', 'open', 'strategyId', v_strategy_id,
    'maxLoss', v_max_loss, 'maxProfit', v_max_profit,
    'breakEvenPrice', v_break_even, 'idempotentReplay', false
  );
end;
$$;

create or replace function public.simulate_options_paper_event(
  p_user_id uuid,
  p_portfolio_id uuid,
  p_strategy_id uuid,
  p_client_event_id text,
  p_event_type text,
  p_settlement_price numeric
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_strategy public.options_paper_strategies%rowtype;
  v_existing uuid;
  v_event_id uuid;
  v_journal_id uuid;
  v_payoff_per_share numeric(24,8) := 0;
  v_cash_effect numeric(24,8) := 0;
  v_realized_pnl numeric(24,8);
  v_status text;
begin
  if current_setting('request.jwt.claim.role', true) <> 'service_role' then
    raise exception 'Options paper events require the simulation service';
  end if;
  if char_length(coalesce(p_client_event_id, '')) not between 8 and 100
    or p_event_type not in ('expiration', 'exercise', 'assignment', 'early_assignment', 'corporate_action') then
    raise exception 'Invalid options paper event';
  end if;

  select id into v_existing from public.options_paper_events
  where user_id = p_user_id and client_event_id = p_client_event_id;
  if v_existing is not null then
    return jsonb_build_object('status', 'recorded', 'eventId', v_existing, 'idempotentReplay', true);
  end if;

  select * into v_strategy from public.options_paper_strategies
  where id = p_strategy_id and portfolio_id = p_portfolio_id and user_id = p_user_id for update;
  if v_strategy.id is null or v_strategy.lifecycle_status not in ('open', 'adjusted') then
    raise exception 'Options paper strategy is unavailable';
  end if;

  if p_event_type = 'corporate_action' then
    insert into public.options_paper_events (
      user_id, portfolio_id, strategy_id, client_event_id, event_type,
      settlement_price, cash_effect, event_note
    ) values (
      p_user_id, p_portfolio_id, p_strategy_id, p_client_event_id,
      p_event_type, null, 0, 'Deterministic corporate-action adjustment rehearsal; no real contract or position changed.'
    ) returning id into v_event_id;
    update public.options_paper_strategies set lifecycle_status = 'adjusted'
    where id = p_strategy_id;
    return jsonb_build_object('status', 'adjusted', 'eventId', v_event_id, 'cashEffect', 0, 'idempotentReplay', false);
  end if;

  if p_settlement_price is null or p_settlement_price < 0 then
    raise exception 'A non-negative scenario settlement price is required';
  end if;
  if p_event_type in ('assignment', 'early_assignment') and not exists (
    select 1 from public.options_paper_legs where strategy_id = p_strategy_id and side = 'short'
  ) then
    raise exception 'Assignment requires a protected short leg';
  end if;

  select coalesce(sum(
    (case
      when chain.option_type = 'call' then greatest(p_settlement_price - chain.strike, 0)
      else greatest(chain.strike - p_settlement_price, 0)
    end)
    * case when leg.side = 'long' then leg.ratio else -leg.ratio end
  ), 0)
  into v_payoff_per_share
  from public.options_paper_legs leg
  join public.options_chain_scenarios chain on chain.id = leg.contract_id
  where leg.strategy_id = p_strategy_id;

  v_cash_effect := greatest(v_payoff_per_share * v_strategy.contract_multiplier * v_strategy.contracts, 0);
  v_realized_pnl := v_cash_effect - v_strategy.max_loss;
  v_status := case p_event_type
    when 'expiration' then 'expired'
    when 'exercise' then 'exercised'
    when 'assignment' then 'assigned'
    when 'early_assignment' then 'early_assigned'
  end;

  insert into public.options_paper_events (
    user_id, portfolio_id, strategy_id, client_event_id, event_type,
    settlement_price, cash_effect, realized_pnl, event_note
  ) values (
    p_user_id, p_portfolio_id, p_strategy_id, p_client_event_id,
    p_event_type, p_settlement_price, v_cash_effect, v_realized_pnl,
    'Deterministic options lifecycle rehearsal with virtual cash settlement only.'
  ) returning id into v_event_id;

  if v_cash_effect > 0 then
    update public.options_paper_accounts set cash_balance = cash_balance + v_cash_effect
    where portfolio_id = p_portfolio_id and user_id = p_user_id;
    insert into public.options_paper_journal_entries (
      user_id, portfolio_id, strategy_id, event_id, entry_type, correlation_id
    ) values (
      p_user_id, p_portfolio_id, p_strategy_id, v_event_id,
      'virtual_settlement', p_client_event_id
    ) returning id into v_journal_id;
    insert into public.options_paper_journal_lines (journal_entry_id, account_code, amount)
    values
      (v_journal_id, 'virtual_cash', v_cash_effect),
      (v_journal_id, 'option_settlement', -v_cash_effect);
  end if;

  update public.options_paper_strategies
  set lifecycle_status = v_status, realized_pnl = v_realized_pnl
  where id = p_strategy_id;

  return jsonb_build_object(
    'status', v_status, 'eventId', v_event_id,
    'cashEffect', v_cash_effect, 'realizedPnl', v_realized_pnl,
    'idempotentReplay', false
  );
end;
$$;

create or replace function public.reconcile_options_paper_portfolio(
  p_user_id uuid,
  p_portfolio_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_unbalanced integer;
  v_uncovered integer;
  v_risk integer;
  v_cash integer;
  v_status text;
  v_expected numeric(24,8);
  v_actual numeric(24,8);
begin
  if current_setting('request.jwt.claim.role', true) <> 'service_role' then
    raise exception 'Options reconciliation requires the simulation service';
  end if;
  select cash_balance, starting_cash into v_actual, v_expected
  from public.options_paper_accounts
  where portfolio_id = p_portfolio_id and user_id = p_user_id;
  if v_actual is null then raise exception 'Options paper account is unavailable'; end if;

  select count(*)::integer into v_unbalanced from (
    select line.journal_entry_id
    from public.options_paper_journal_lines line
    join public.options_paper_journal_entries journal on journal.id = line.journal_entry_id
    where journal.portfolio_id = p_portfolio_id and journal.user_id = p_user_id
    group by line.journal_entry_id, line.currency
    having abs(sum(line.amount)) > 0.00000001
  ) exceptions;

  select count(*)::integer into v_uncovered
  from public.options_paper_strategies strategy
  where strategy.portfolio_id = p_portfolio_id and strategy.user_id = p_user_id
    and exists (select 1 from public.options_paper_legs where strategy_id = strategy.id and side = 'short')
    and not exists (select 1 from public.options_paper_legs where strategy_id = strategy.id and side = 'long');

  select count(*)::integer into v_risk
  from public.options_paper_strategies
  where portfolio_id = p_portfolio_id and user_id = p_user_id
    and (not defined_risk or loss_risk <> 'bounded' or max_loss is null
      or collateral_amount < max_loss
      or (profit_potential = 'unbounded' and strategy_type <> 'long_call'));

  v_expected := v_expected
    - coalesce((select sum(max_loss) from public.options_paper_strategies
      where portfolio_id = p_portfolio_id and user_id = p_user_id), 0)
    + coalesce((select sum(cash_effect) from public.options_paper_events
      where portfolio_id = p_portfolio_id and user_id = p_user_id), 0);
  v_cash := case when abs(v_expected - v_actual) > 0.00000001 then 1 else 0 end;
  v_status := case when v_unbalanced + v_uncovered + v_risk + v_cash = 0 then 'passed' else 'exception' end;

  insert into public.options_paper_reconciliations (
    user_id, portfolio_id, status, unbalanced_journals,
    uncovered_short_legs, risk_boundary_exceptions, cash_mismatches
  ) values (
    p_user_id, p_portfolio_id, v_status, v_unbalanced,
    v_uncovered, v_risk, v_cash
  );
  return jsonb_build_object(
    'status', v_status, 'unbalancedJournals', v_unbalanced,
    'uncoveredShortLegs', v_uncovered, 'riskBoundaryExceptions', v_risk,
    'cashMismatches', v_cash
  );
end;
$$;

