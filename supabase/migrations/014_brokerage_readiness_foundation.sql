create table if not exists public.broker_provider_registry (
  id bigint generated by default as identity primary key,
  code text not null unique check (code ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  display_name text not null,
  adapter_contract_version text not null,
  regulatory_status text not null default 'unreviewed' check (
    regulatory_status in ('unreviewed', 'due_diligence', 'approved', 'suspended')
  ),
  integration_status text not null default 'planned' check (
    integration_status in ('planned', 'sandbox', 'certification', 'production_disabled')
  ),
  supported_jurisdictions jsonb not null default '[]'::jsonb check (
    jsonb_typeof(supported_jurisdictions) = 'array'
  ),
  supported_asset_classes jsonb not null default '[]'::jsonb check (
    jsonb_typeof(supported_asset_classes) = 'array'
  ),
  account_connection_enabled boolean not null default false,
  live_order_routing_enabled boolean not null default false check (not live_order_routing_enabled),
  metadata jsonb not null default '{}'::jsonb check (jsonb_typeof(metadata) = 'object'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.brokerage_execution_controls (
  control_key text primary key check (control_key = 'global-live-orders'),
  execution_enabled boolean not null default false check (not execution_enabled),
  preview_enabled boolean not null default true,
  required_approvals jsonb not null check (jsonb_typeof(required_approvals) = 'array'),
  recorded_approvals jsonb not null default '[]'::jsonb check (
    jsonb_typeof(recorded_approvals) = 'array'
  ),
  policy_version text not null,
  last_reviewed_at timestamptz,
  updated_at timestamptz not null default now()
);

create table if not exists public.brokerage_accounts (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  provider_id bigint not null references public.broker_provider_registry(id),
  account_alias text not null check (char_length(account_alias) between 2 and 80),
  account_type text not null default 'cash' check (
    account_type in ('cash', 'margin', 'retirement', 'institutional')
  ),
  base_currency text not null default 'USD' check (base_currency ~ '^[A-Z]{3}$'),
  connection_status text not null default 'pending' check (
    connection_status in ('pending', 'review', 'connected', 'restricted', 'closed')
  ),
  environment text not null default 'sandbox' check (environment = 'sandbox'),
  capabilities jsonb not null default '[]'::jsonb check (jsonb_typeof(capabilities) = 'array'),
  last_synchronized_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, provider_id, account_alias),
  unique (id, user_id)
);

create table if not exists public.brokerage_readiness_checks (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  check_type text not null check (
    check_type in (
      'identity',
      'residency',
      'sanctions',
      'aml',
      'suitability',
      'disclosures',
      'broker_account',
      'funding_source'
    )
  ),
  status text not null default 'not_started' check (
    status in ('not_started', 'pending', 'passed', 'failed', 'review', 'expired')
  ),
  policy_version text not null,
  evidence_summary jsonb not null default '{}'::jsonb check (
    jsonb_typeof(evidence_summary) = 'object'
  ),
  reviewed_at timestamptz,
  expires_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, check_type),
  check (expires_at is null or reviewed_at is null or expires_at > reviewed_at)
);

create table if not exists public.brokerage_disclosures (
  id uuid primary key default gen_random_uuid(),
  code text not null check (code ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  version text not null,
  jurisdiction_code text references public.jurisdictions(country_code),
  title text not null,
  summary text not null,
  document_url text,
  required boolean not null default true,
  published boolean not null default false,
  effective_at timestamptz not null,
  superseded_at timestamptz,
  created_at timestamptz not null default now(),
  unique (code, version),
  check (superseded_at is null or superseded_at > effective_at)
);

create table if not exists public.brokerage_consents (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  disclosure_id uuid not null references public.brokerage_disclosures(id),
  consent_method text not null default 'authenticated_clickwrap' check (
    consent_method = 'authenticated_clickwrap'
  ),
  disclosure_version text not null,
  accepted_at timestamptz not null default now(),
  revoked_at timestamptz,
  created_at timestamptz not null default now(),
  unique (user_id, disclosure_id),
  check (revoked_at is null or revoked_at > accepted_at)
