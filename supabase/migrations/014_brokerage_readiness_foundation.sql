create table if not exists public.brokerage_order_previews (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  client_request_id uuid not null,
  brokerage_account_id uuid,
  instrument_id bigint not null references public.investment_instruments(id),
  side text not null check (side in ('buy', 'sell')),
  order_type text not null check (order_type in ('market', 'limit')),
  quantity numeric(24,8) not null check (quantity > 0),
  limit_price numeric(20,8) check (limit_price is null or limit_price > 0),
  reference_price numeric(20,8),
  estimated_notional numeric(24,8),
  quote_currency text not null check (quote_currency ~ '^[A-Z]{3}$'),
  preview_status text not null default 'blocked' check (preview_status = 'blocked'),
  executable boolean not null default false check (not executable),
  block_reasons jsonb not null check (
    jsonb_typeof(block_reasons) = 'array' and jsonb_array_length(block_reasons) > 0
  ),
  policy_version text not null,
  reference_observed_at timestamptz,
  expires_at timestamptz not null,
  created_at timestamptz not null default now(),
  unique (user_id, client_request_id),
  foreign key (brokerage_account_id, user_id)
    references public.brokerage_accounts(id, user_id),
  check (order_type <> 'limit' or limit_price is not null),
  check (reference_price is null or reference_price > 0),
  check (estimated_notional is null or estimated_notional > 0),
  check (expires_at > created_at)
);

