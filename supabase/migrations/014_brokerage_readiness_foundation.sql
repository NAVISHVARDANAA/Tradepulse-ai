create or replace view public.brokerage_readiness_dashboard
with (security_invoker = true)
as
select
  investor.user_id,
  investor.declared_residency_country,
  investor.verified_residency_country,
  investor.base_currency,
  investor.investor_type,
  investor.risk_tolerance,
  investor.kyc_status,
  investor.suitability_status,
  investor.sanctions_status,
  investor.onboarding_state,
  investor.compliance_reviewed_at,
  jurisdiction.availability_status as jurisdiction_status,
  coalesce(jurisdiction.retail_investing_enabled, false) as retail_investing_enabled,
  control.execution_enabled,
  control.preview_enabled,
  control.required_approvals,
  control.recorded_approvals,
  control.policy_version,
  (
    select count(*)::integer
    from public.brokerage_disclosures disclosure
    where disclosure.required
      and disclosure.published
      and disclosure.effective_at <= now()
      and (disclosure.superseded_at is null or disclosure.superseded_at > now())
  ) as required_disclosures,
  (
    select count(*)::integer
    from public.brokerage_consents consent
    join public.brokerage_disclosures disclosure on disclosure.id = consent.disclosure_id
    where consent.user_id = investor.user_id
      and consent.revoked_at is null
      and consent.disclosure_version = disclosure.version
      and disclosure.required
      and disclosure.published
      and (disclosure.superseded_at is null or disclosure.superseded_at > now())
  ) as accepted_disclosures,
  (
    select count(*)::integer
    from public.brokerage_accounts account
    where account.user_id = investor.user_id
      and account.connection_status = 'connected'
      and account.environment = 'sandbox'
  ) as connected_sandbox_accounts
from public.user_investor_profiles investor
left join public.jurisdictions jurisdiction
  on jurisdiction.country_code = investor.verified_residency_country
cross join public.brokerage_execution_controls control
where investor.user_id = auth.uid()
  and control.control_key = 'global-live-orders';

grant select on public.brokerage_readiness_dashboard to authenticated;

do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    if not exists (
      select 1 from pg_publication_tables
      where pubname = 'supabase_realtime'
        and schemaname = 'public'
        and tablename = 'brokerage_order_previews'
    ) then
      execute 'alter publication supabase_realtime add table public.brokerage_order_previews';
    end if;
  end if;
end;
$$;

