create or replace function public.record_brokerage_consent(p_disclosure_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  current_user uuid := auth.uid();
  disclosure_record public.brokerage_disclosures%rowtype;
  consent_record public.brokerage_consents%rowtype;
begin
  if current_user is null then
    raise exception 'Authentication is required';
  end if;

  select * into disclosure_record
  from public.brokerage_disclosures
  where id = p_disclosure_id
    and published
    and effective_at <= now()
    and (superseded_at is null or superseded_at > now());

  if disclosure_record.id is null then
    raise exception 'Current disclosure not found';
  end if;

  insert into public.brokerage_consents (
    user_id,
    disclosure_id,
    disclosure_version,
    accepted_at,
    revoked_at
  ) values (
    current_user,
    disclosure_record.id,
    disclosure_record.version,
    now(),
    null
  )
  on conflict (user_id, disclosure_id) do update
  set
    disclosure_version = excluded.disclosure_version,
    accepted_at = excluded.accepted_at,
    revoked_at = null
  returning * into consent_record;

  insert into public.financial_audit_events (
    user_id,
    event_type,
    resource_type,
    resource_id,
    actor_type,
    correlation_id,
    details
  ) values (
    current_user,
    'brokerage_disclosure_accepted',
    'brokerage_disclosure',
    disclosure_record.id::text,
    'user',
    consent_record.id::text,
    jsonb_build_object('code', disclosure_record.code, 'version', disclosure_record.version)
  );

  return jsonb_build_object(
    'id', consent_record.id,
    'disclosureId', consent_record.disclosure_id,
    'version', consent_record.disclosure_version,
    'acceptedAt', consent_record.accepted_at
  );
end;
$$;

revoke all on function public.record_brokerage_consent(uuid) from public;
grant execute on function public.record_brokerage_consent(uuid) to authenticated;

create or replace function public.persist_brokerage_order_preview(
  p_user_id uuid,
  p_client_request_id uuid,
  p_brokerage_account_id uuid,
  p_instrument_id bigint,
  p_side text,
  p_order_type text,
  p_quantity numeric,
  p_limit_price numeric,
  p_reference_price numeric,
  p_estimated_notional numeric,
  p_quote_currency text,
  p_block_reasons jsonb,
  p_policy_version text,
  p_reference_observed_at timestamptz,
  p_expires_at timestamptz
)
returns public.brokerage_order_previews
language plpgsql
security definer
set search_path = public
as $$
declare
  preview_record public.brokerage_order_previews%rowtype;
begin
  if auth.role() <> 'service_role' then
    raise exception 'This operation requires the brokerage-readiness service';
  end if;

  insert into public.brokerage_order_previews (
    user_id,
    client_request_id,
    brokerage_account_id,
    instrument_id,
    side,
    order_type,
    quantity,
    limit_price,
    reference_price,
    estimated_notional,
    quote_currency,
    preview_status,
    executable,
    block_reasons,
    policy_version,
    reference_observed_at,
    expires_at
  ) values (
    p_user_id,
    p_client_request_id,
    p_brokerage_account_id,
    p_instrument_id,
    p_side,
    p_order_type,
    p_quantity,
    p_limit_price,
    p_reference_price,
    p_estimated_notional,
    p_quote_currency,
    'blocked',
    false,
    p_block_reasons,
    p_policy_version,
    p_reference_observed_at,
    p_expires_at
  )
  on conflict (user_id, client_request_id) do nothing
  returning * into preview_record;

  if preview_record.id is null then
    select * into preview_record
    from public.brokerage_order_previews
    where user_id = p_user_id
      and client_request_id = p_client_request_id;
    return preview_record;
  end if;

  insert into public.financial_audit_events (
    user_id,
    event_type,
    resource_type,
    resource_id,
    actor_type,
    correlation_id,
    details
  ) values (
    p_user_id,
    'brokerage_order_preview_blocked',
    'brokerage_order_preview',
    preview_record.id::text,
    'user',
    p_client_request_id::text,
    jsonb_build_object(
      'instrumentId', p_instrument_id,
      'side', p_side,
      'quantity', p_quantity,
      'executable', false,
      'blockReasonCodes', (
        select coalesce(jsonb_agg(item -> 'code'), '[]'::jsonb)
        from jsonb_array_elements(p_block_reasons) item
      )
    )
  );

  return preview_record;
end;
$$;

