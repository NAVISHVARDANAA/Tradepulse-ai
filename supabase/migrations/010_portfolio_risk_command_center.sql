create or replace function public.initialize_paper_control_state()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.portfolio_type = 'paper' then
    insert into public.portfolio_control_states (portfolio_id)
    values (new.id)
    on conflict (portfolio_id) do nothing;
  end if;

  return new;
end;
$$;

