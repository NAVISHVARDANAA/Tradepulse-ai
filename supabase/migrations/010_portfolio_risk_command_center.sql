-- TradePulse AI
-- Migration 010: Portfolio risk command center and paper reconciliation
-- These controls monitor simulation portfolios only. They cannot route live orders.

alter table public.portfolio_risk_limits
  add column if not exists max_concentration_percent numeric(8,4) not null default 40
    check (max_concentration_percent > 0 and max_concentration_percent <= 100),
  add column if not exists max_drawdown_percent numeric(8,4) not null default 15
    check (max_drawdown_percent > 0 and max_drawdown_percent <= 100),
  add column if not exists var_limit numeric(24,8) not null default 7500
    check (var_limit > 0),
  add column if not exists minimum_cash_percent numeric(8,4) not null default 5
    check (minimum_cash_percent >= 0 and minimum_cash_percent <= 100),
  add column if not exists auto_kill_switch boolean not null default true;

create table if not exists public.portfolio_control_states (
  portfolio_id uuid primary key references public.investment_portfolios(id) on delete cascade,
  trading_enabled boolean not null default true,
  kill_switch_active boolean not null default false,
  trigger_source text check (trigger_source in ('user', 'system', 'administrator')),
  reason text,
  requires_review boolean not null default false,
  activated_at timestamptz,
  updated_at timestamptz not null default now(),
  check (trading_enabled <> kill_switch_active)
);

create table if not exists public.portfolio_risk_snapshots (
  id bigint generated by default as identity primary key,
  portfolio_id uuid not null references public.investment_portfolios(id) on delete cascade,
  observed_at timestamptz not null,
  total_value numeric(24,8) not null,
  cash_value numeric(24,8) not null,
  gross_exposure numeric(24,8) not null,
  net_exposure numeric(24,8) not null,
  daily_pnl numeric(24,8),
  concentration_percent numeric(12,8) not null default 0,
  cash_percent numeric(12,8) not null default 0,
  drawdown_percent numeric(12,8) not null default 0,
  var_95_one_day numeric(24,8) not null default 0,
  scenario_count integer not null default 0,
  position_count integer not null default 0,
  stale_price_count integer not null default 0,
  breaches jsonb not null default '[]'::jsonb,
  breach_count integer not null default 0,
  model_version text not null default 'paper-risk-v2',
  created_at timestamptz not null default now(),
  unique (portfolio_id, observed_at)
);

create table if not exists public.paper_reconciliation_runs (
  id uuid primary key default gen_random_uuid(),
  portfolio_id uuid not null references public.investment_portfolios(id) on delete cascade,
  status text not null default 'running' check (
    status in ('running', 'completed', 'exception', 'failed')
  ),
  recorded_cash numeric(24,8),
  ledger_cash numeric(24,8),
  cash_difference numeric(24,8),
  positions_checked integer not null default 0,
  issues_found integer not null default 0,
  details jsonb not null default '{}'::jsonb,
  started_at timestamptz not null default now(),
  completed_at timestamptz
);

create table if not exists public.paper_reconciliation_issues (
  id bigint generated by default as identity primary key,
  reconciliation_run_id uuid not null
    references public.paper_reconciliation_runs(id) on delete cascade,
  issue_type text not null check (
    issue_type in ('cash_mismatch', 'position_mismatch', 'missing_price')
  ),
  severity text not null check (severity in ('warning', 'critical')),
  resource_id text,
  expected_value numeric(24,8),
  actual_value numeric(24,8),
  status text not null default 'open' check (status in ('open', 'resolved')),
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  resolved_at timestamptz
);

create index if not exists idx_risk_snapshots_portfolio_observed
  on public.portfolio_risk_snapshots(portfolio_id, observed_at desc);

create index if not exists idx_reconciliation_runs_portfolio_started
  on public.paper_reconciliation_runs(portfolio_id, started_at desc);

create index if not exists idx_reconciliation_issues_run
  on public.paper_reconciliation_issues(reconciliation_run_id, status);

